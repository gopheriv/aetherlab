"""Mock worked math is shared by languages and visible after completion."""
from __future__ import annotations

import math
import os
import re
from fractions import Fraction

import pytest

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from aetherlab.services.ent_physics_bank import mock_questions_for_language, questions_for_language
from aetherlab.ui.exam_practice import ExamPracticeDialog
from aetherlab.ui.qt_compat import QtCore, QtGui, QtWidgets

_APP = None


def _app():
    global _APP
    _APP = QtWidgets.QApplication.instance() or QtWidgets.QApplication([])
    return _APP


def test_every_mock_has_shared_renderable_worked_math():
    _app()
    from aetherlab.services.mathtext import render_math

    banks = [mock_questions_for_language(language) for language in ("kk", "ru", "en")]
    for translations in zip(*banks):
        assert len({q["id"] for q in translations}) == 1
        formulas = translations[0]["solution_latex"]
        assert formulas, translations[0]["id"]
        assert all(q["solution_latex"] == formulas for q in translations)
        assert all(q["correct_indices"] == translations[0]["correct_indices"] for q in translations)
        for formula in formulas:
            pixmap = render_math(formula, px_size=20, color="#18283D")
            assert pixmap is not None and not pixmap.isNull(), (translations[0]["id"], formula)


def test_numerical_mock_keys_and_worked_answers_match_independent_calculation():
    # Calculations use the actual fixed conditions, not text generated by an LLM.
    cases = {
        "kinematics-velocity-01": (2 + 3 * 4, "14"),
        "dynamics-freefall-01": (10 * 2, "20"),
        "electricity-ohm-01": (Fraction(12, 6), "2"),
        "energy-kinetic-01": (Fraction(2 * 3**2, 2), "9"),
        "waves-period-01": (Fraction(1, 5), "0.2"),
        "statics-moment-01": (Fraction(40 * 20, 50), "16"),
        "fluids-pressure-01": (1000 * 10 * 3 / 1000, "30"),
        "gas-law-pressure-01": (Fraction(100 * 450, 300), "150"),
        "thermodynamics-first-law-01": (500 - 200, "300"),
        "materials-melting-01": (Fraction(330000, 2 * 1000), "165"),
        "induction-emf-01": (Fraction(40, 10), "4"),
        "oscillation-frequency-01": (Fraction(10, 25), "0.4"),
        # This question explicitly requests an approximate whole-volt answer.
        "ac-rms-voltage-01": (round(311 / 1.414), "220"),
        "wave-optics-fringe-01": (500e-9 * 2 / 1e-3 * 1000, "1"),
        "geometric-optics-lens-01": (1 / (Fraction(1, 10) - Fraction(1, 30)), "15"),
        "relativity-gamma-01": (1 / math.sqrt(1 - 0.6**2), "1.25"),
        "context-solar-heater-energy-01": (4200 * 2 * (30 - 20) / 1000, "84"),
        "context-solar-heater-power-02": (84000 / (20 * 60), "70"),
        "context-solar-heater-height-03": (2 * 10 * 5, "100"),
        "context-solar-heater-efficiency-04": (84 / 120 * 100, "70"),
        "context-solar-heater-volume-05": (1000 * 10 * 5 / 1000, "50"),
    }
    bank = {q["id"]: q for q in mock_questions_for_language("en")}
    for question_id, (computed, shown) in cases.items():
        assert math.isclose(float(computed), float(shown), rel_tol=0.0002), question_id
        question = bank[question_id]
        key_value = re.match(r"[0-9]+(?:\.[0-9]+)?", question["answer"])
        assert key_value and math.isclose(float(key_value.group()), float(computed), rel_tol=0.0002), question_id
        assert question["solution_latex"], question_id
        worked_value = re.search(r"(?:=|\\approx)([0-9]+(?:\.[0-9]+)?)(?:\\,\\mathrm\{[^{}]+\}|\\%|)$", question["solution_latex"][-1])
        assert worked_value and math.isclose(float(worked_value.group(1)), float(computed), rel_tol=0.0002), question_id


@pytest.mark.parametrize("language", ("kk", "ru", "en"))
@pytest.mark.parametrize("mode", ("practice", "timed"))
def test_completed_review_contains_typeset_equations_and_clears_previous_resources(language, mode, tmp_path):
    _app()
    bank = mock_questions_for_language(language) if mode == "timed" else questions_for_language(language)
    dialog = ExamPracticeDialog(language, progress_path=tmp_path / f"{language}-{mode}.json")
    dialog._begin_session(bank[:1], mode)
    if mode == "timed":
        assert dialog._solution_math.isHidden()
    dialog._answers[0] = tuple(bank[0]["correct_indices"])
    dialog._finish_session()
    html = dialog._review.toHtml()
    assert "physlab-review-equation:" in html, "Results omit the question's typeset solution"
    document = dialog._review.document()
    found = []
    block = document.begin()
    while block.isValid():
        iterator = block.begin()
        while not iterator.atEnd():
            fragment = iterator.fragment()
            if fragment.charFormat().isImageFormat():
                fmt = fragment.charFormat().toImageFormat()
                image = document.resource(QtGui.QTextDocument.ResourceType.ImageResource, QtCore.QUrl(fmt.name()))
                assert image is not None and not image.isNull()
                assert fmt.width() > 0 and fmt.height() > 0
                found.append(fmt.name())
            iterator += 1
        block = block.next()
    assert len(found) == len(bank[0]["solution_latex"])
    assert "\\frac" not in dialog._review.toPlainText()
    old_document = document
    dialog._begin_session(bank[1:2], mode)
    dialog._finish_session()
    assert dialog._review.document() is not old_document
    assert all(name not in dialog._review.toHtml() for name in found)
    dialog.close()


@pytest.mark.parametrize("language", ("kk", "ru", "en"))
def test_full_mock_pdf_contains_all_shared_equations(language, tmp_path):
    _app()
    import fitz

    from aetherlab.services.ent_practice_pdf import export_practice_pdf
    from aetherlab.ui.exam_practice import _TOPIC_NAMES

    questions = mock_questions_for_language(language)
    output = export_practice_pdf(
        tmp_path / f"mock-{language}.pdf", language=language, questions=questions,
        user_answers=[q["answer"] for q in questions], topic_names=_TOPIC_NAMES[language],
        topic_progress={}, score=50, possible_points=50, scored_question_count=40,
        question_counted=[True] * 40, question_points=[1 if q["kind"] in {"single", "context"} else 2 for q in questions],
    )
    with fitz.open(output) as report:
        text = "\n".join(page.get_text() for page in report)
        assert "50/50" in text
        assert "\\frac" not in text
        assert sum(len(page.get_images()) for page in report) >= sum(len(q["solution_latex"]) for q in questions)
        assert all(page.rect.width > 0 and page.rect.height > 0 for page in report)


def test_typeset_failure_keeps_readable_math_and_never_shows_raw_latex(tmp_path, monkeypatch):
    _app()
    from aetherlab.services import mathtext

    monkeypatch.setattr(mathtext, "render_math", lambda *args, **kwargs: None)
    dialog = ExamPracticeDialog("ru", progress_path=tmp_path / "fallback.json")
    question = questions_for_language("ru", "kinematics")[0]
    dialog._begin_session((question,), "practice")
    dialog._answers[0] = tuple(question["correct_indices"])
    dialog._show_feedback(question)
    equations = [dialog._solution_math_layout.itemAt(i).widget().text() for i in range(dialog._solution_math_layout.count())]
    assert equations and all("\\" not in value for value in equations)
    dialog._finish_session()
    assert "physlab-review-equation:" not in dialog._review.toHtml()
    assert "\\" not in dialog._review.toPlainText()
    assert "v₀" in dialog._review.toPlainText()
    assert "не удалось" in dialog._readable_solution_formula(r"\unknown{x}").lower()
    dialog.close()
