"""Curated component: thin-lens image formation by ray tracing.

Geometric optics had no reliable (non-LLM) visual. This draws the textbook ray
diagram for a converging lens: an object, the three principal rays (the parallel
ray bending through the far focus, the chief ray straight through the centre, and
the focal ray emerging parallel), and the real inverted image where they
reconverge — with the image position from the thin-lens equation 1/f = 1/do + 1/di.
A light pulse travels along a ray so the frame moves.

Deterministic and self-contained (``manim`` + ``numpy`` only). Selected on
lens / refraction / focal-length / image-formation phrasing.
"""

from __future__ import annotations

from typing import Any


def params(solver: Any) -> dict[str, float]:
    """Resolved lens geometry; shared by build() and explain()."""
    variables = {str(k): float(v) for k, v in dict(getattr(solver, "variables", {}) or {}).items()}
    f = _clamp(variables.get("focal_length", variables.get("f", 1.8)), 1.0, 2.6)
    do = _clamp(variables.get("object_distance", variables.get("distance", 3.6)), f + 0.8, 5.2)
    ho = _clamp(variables.get("height", variables.get("object_height", 1.2)), 0.6, 1.8)

    di = 1.0 / (1.0 / f - 1.0 / do)   # do > f guaranteed → real image
    hi = -ho * di / do
    return {"f": f, "do": do, "ho": ho, "di": di, "hi": hi}


def build(class_name: str, solver: Any) -> str | None:
    """Return a thin-lens ray-diagram scene. Never needs solver data."""
    variables = {str(k): float(v) for k, v in dict(getattr(solver, "variables", {}) or {}).items()}
    focal = variables.get("focal_length", variables.get("f"))
    object_distance = variables.get("object_distance", variables.get("distance"))
    object_height = variables.get("height", variables.get("object_height"))
    # This component depicts a converging lens with a real, inverted image.
    # Reject known input that would require a diverging lens, a virtual image,
    # or geometry outside the scene's supported scale instead of clamping it
    # into a physically different example.
    if focal is not None and not 1.0 <= focal <= 2.6:
        return None
    if object_distance is not None and not 1.8 <= object_distance <= 5.2:
        return None
    if focal is not None and object_distance is not None and object_distance <= focal + 0.8:
        return None
    if object_height is not None and not 0.6 <= object_height <= 1.8:
        return None
    p = params(solver)
    f, do, ho, di, hi = p["f"], p["do"], p["ho"], p["di"], p["hi"]

    title = _shorten(getattr(solver, "summary", "") or "Thin-lens image formation", 60)
    return _TEMPLATE.format(
        class_name=class_name,
        f=repr(round(f, 4)), do=repr(round(do, 4)), di=repr(round(di, 4)),
        ho=repr(round(ho, 4)), hi=repr(round(hi, 4)),
        title=repr(title),
    )


def _clamp(value: Any, lo: float, hi: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        v = lo
    return max(lo, min(hi, v))


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - thin-lens ray diagram (curated component)."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        f, do, di = {f}, {do}, {di}
        ho, hi = {ho}, {hi}

        title = Text({title}).scale(0.46).to_edge(UP)

        def P(x, y):
            return np.array([float(x), float(y), 0.0])

        axis = Line(P(-6.4, 0), P(6.4, 0), color=GREY_B, stroke_width=2, stroke_opacity=0.6)
        lens = Ellipse(width=0.5, height=4.0, color=BLUE_C, fill_color=BLUE_E,
                       fill_opacity=0.25, stroke_width=2.5)
        f_near = Dot(P(-f, 0), color=GREY_A, radius=0.05)
        f_far = Dot(P(f, 0), color=GREY_A, radius=0.05)
        f_lbl1 = Text("F").scale(0.32).next_to(f_near, DOWN, buff=0.12)
        f_lbl2 = Text("F'").scale(0.32).next_to(f_far, DOWN, buff=0.12)

        obj = Arrow(P(-do, 0), P(-do, ho), buff=0, color=GREEN, stroke_width=4)
        img = Arrow(P(di, 0), P(di, hi), buff=0, color=RED, stroke_width=4)
        obj_lbl = Text("object").scale(0.3).next_to(obj, UP, buff=0.1)
        img_lbl = Text("real image (inverted)").scale(0.3).next_to(img, DOWN, buff=0.1)

        tip = P(-do, ho)
        itip = P(di, hi)
        # Ray 1: parallel to axis, then through the far focus F'.
        ray1 = VMobject(color=YELLOW, stroke_width=2.5)
        ray1.set_points_as_corners([tip, P(0, ho), itip])
        # Ray 2: straight through the lens centre.
        ray2 = VMobject(color=GOLD, stroke_width=2.5)
        ray2.set_points_as_corners([tip, P(0, 0), itip])
        # Ray 3: through the near focus F, emerging parallel to the axis.
        ray3 = VMobject(color=ORANGE, stroke_width=2.5)
        ray3.set_points_as_corners([tip, P(0, hi), itip])

        pulse = Dot(tip, color=WHITE, radius=0.06)

        self.play(Create(axis), Create(lens), run_time=0.9)
        self.play(FadeIn(f_near), FadeIn(f_far), FadeIn(f_lbl1), FadeIn(f_lbl2), run_time=0.5)
        self.play(GrowArrow(obj), FadeIn(obj_lbl), run_time=0.7)
        self.play(Create(ray1), Create(ray2), Create(ray3), run_time=2.0)
        self.add(pulse)
        self.play(MoveAlongPath(pulse, ray1), run_time=1.4, rate_func=linear)
        self.play(GrowArrow(img), FadeIn(img_lbl), run_time=0.8)
        self.wait(0.6)
'''
