"""Curated component: a quantum wavepacket sloshing in a potential well.

The quantum domain had no reliable (non-LLM) visual. This stages the canonical
picture: a harmonic potential well V(x) = ½kx², a few energy levels, and a
Gaussian probability density |ψ(x,t)|² (a coherent state) oscillating back and
forth in the well with its area shaded — so the abstract wavefunction reads as a
concrete lump of probability moving in a landscape.

Deterministic and self-contained (``manim`` + ``numpy`` only). Selected when the
prompt is about quantum mechanics / wavefunctions / wavepackets.
"""

from __future__ import annotations

import math
from typing import Any


def params(solver: Any) -> dict[str, float]:
    """Resolved well parameters; shared by build() and explain()."""
    variables = {str(k): v for k, v in dict(getattr(solver, "variables", {}) or {}).items()}
    stiffness = _positive(variables.get("stiffness", variables.get("k")), 1.0)
    mass = _positive(variables.get("mass", variables.get("m")), 1.0)
    return {
        # Classical frequency of the coherent state sloshing in the well.
        "omega": _clamp(math.sqrt(stiffness / mass), 0.6, 1.7),
        "amplitude": _clamp(variables.get("amplitude", variables.get("x0", 2.6)), 1.4, 3.0),
    }


def build(class_name: str, solver: Any) -> str | None:
    """Return a quantum-wavepacket scene, parameterized by the well when given."""
    p = params(solver)
    omega, amp = p["omega"], p["amplitude"]

    title = _shorten(getattr(solver, "summary", "") or "Quantum wavepacket in a well", 60)
    return _TEMPLATE.format(
        class_name=class_name, omega=repr(round(omega, 4)), amp=repr(round(amp, 4)),
        title=repr(title),
    )


def _positive(value: Any, default: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        return default
    return v if math.isfinite(v) and v > 1e-6 else default


def _clamp(value: Any, lo: float, hi: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        v = lo
    return max(lo, min(hi, v))


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - quantum wavepacket (curated component)."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        title = Text({title}).scale(0.46).to_edge(UP)

        axes = Axes(
            x_range=[-4.0, 4.0, 1.0], y_range=[0.0, 3.2, 1.0],
            x_length=10.0, y_length=5.0,
            axis_config={{"include_tip": False, "stroke_opacity": 0.45}},
        ).to_edge(DOWN)
        x_label = axes.get_x_axis_label(Text("x").scale(0.4))

        # Harmonic potential well V(x) = 0.5 * k * x^2 (scaled to fit).
        k = 0.32
        well = axes.plot(lambda x: 0.5 * k * x * x, x_range=[-3.6, 3.6], color=BLUE_D)
        well.set_stroke(opacity=0.7)

        # A few quantized energy levels as faint horizontal lines.
        levels = VGroup()
        for e in (0.6, 1.4, 2.4):
            xr = np.sqrt(max(2.0 * e / k, 0.0))
            levels.add(DashedLine(axes.c2p(-xr, e), axes.c2p(xr, e),
                                  color=GREY_B, stroke_width=1.5, stroke_opacity=0.5))

        # Coherent-state probability density: a Gaussian whose centre oscillates.
        amp = {amp}
        omega = {omega}
        sigma = 0.6
        height = 2.4
        grid = np.linspace(-3.8, 3.8, 64)
        t = ValueTracker(0.0)

        def packet():
            x0 = amp * np.cos(omega * t.get_value())
            tops = [axes.c2p(x, height * np.exp(-((x - x0) ** 2) / (2 * sigma ** 2)))
                    for x in grid]
            base = [axes.c2p(x, 0.0) for x in grid[::-1]]
            poly = Polygon(*tops, *base, color=TEAL,
                           fill_color=TEAL, fill_opacity=0.35, stroke_width=2.5)
            return poly

        density = always_redraw(packet)
        psi_tag = Text("|psi(x,t)|^2", color=TEAL).scale(0.34).to_corner(UR, buff=0.7)

        self.play(FadeIn(title), Create(axes), FadeIn(x_label), run_time=1.0)
        self.play(Create(well), LaggedStart(*[Create(l) for l in levels], lag_ratio=0.2),
                  run_time=1.4)
        self.add(density)
        self.play(FadeIn(psi_tag), run_time=0.5)
        self.play(t.animate.set_value(2.0 * PI), run_time=6.5, rate_func=linear)
        self.wait(0.4)
'''
