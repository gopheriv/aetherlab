"""Curated component: a real swinging pendulum driven by numeric ground truth.

Instead of the generic time-series curve (services/scene_components/trajectory)
or the closed-form small-angle approximation baked into the static template,
this integrates the *full nonlinear* pendulum

    theta'' = -(g / L) * sin(theta) - 2 * damping * theta'

through the same scipy path as every other numeric result (services/numeric,
AST-allow-listed RHS — model math is never eval'd), then bakes the exact
theta(t) samples into a self-contained Manim scene: a rod + bob swinging over a
pivot, a comet-tail TracedPath, and a synchronized theta-vs-t readout. The
animation is therefore the real solution (large-angle included), not a curve the
LLM guessed. Depends only on ``manim`` + ``numpy``.
"""

from __future__ import annotations

import math
from typing import Any

_MAX_POINTS = 160


def numeric_spec(theta0: float) -> dict[str, Any]:
    """The nonlinear pendulum ODE animated by build(); explain() measures it."""
    return {
        "state": ["theta", "omega"],
        "rhs": ["omega", "-(gravity/length)*sin(theta) - (2*damping)*omega"],
        "initial": [theta0, 0.0],
        "t_range": [0.0, 12.0],
        "observe": "theta",
    }


def params(solver: Any) -> dict[str, float]:
    """Resolved physical parameters; shared by build() and explain()."""
    variables = {str(k): float(v) for k, v in dict(getattr(solver, "variables", {}) or {}).items()}
    return {
        "gravity": _positive(variables.get("gravity", variables.get("g")), 9.81),
        "length": _positive(variables.get("length", variables.get("l")), 1.0),
        "damping": abs(_finite_or(variables.get("damping", variables.get("friction")), 0.12)),
        "theta0": _initial_angle(variables),
    }


def build(class_name: str, solver: Any) -> str | None:
    """Return a complete Manim pendulum scene, or None when it cannot integrate."""
    p = params(solver)
    gravity, length, damping, theta0 = p["gravity"], p["length"], p["damping"], p["theta0"]

    spec = numeric_spec(theta0)
    try:
        from aetherlab.services.numeric import solve_numeric

        sol = solve_numeric(
            spec, {"gravity": gravity, "length": length, "damping": damping},
            max_points=_MAX_POINTS,
        )
    except Exception:  # noqa: BLE001 — composition must never crash the pipeline
        return None
    if not sol.ok or len(sol.t) < 3:
        return None

    ts = [round(float(v), 5) for v in sol.t]
    ths = [round(float(v), 5) for v in sol.series("theta")]
    if len(ts) != len(ths) or not all(_is_finite(v) for v in ts + ths):
        return None

    title = _shorten(getattr(solver, "summary", "") or "Pendulum", 60)
    return _TEMPLATE.format(
        class_name=class_name,
        ts=repr(ts),
        ths=repr(ths),
        length=repr(round(length, 5)),
        title=repr(title),
    )


def _positive(value: Any, default: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        return default
    return v if math.isfinite(v) and v > 1e-6 else default


def _finite_or(value: Any, default: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        return default
    return v if math.isfinite(v) else default


def _initial_angle(variables: dict[str, float]) -> float:
    """Release angle in radians — from an explicit variable, else a wide swing.

    A 1.0 rad (~57 deg) default is deliberately outside the small-angle regime so
    the nonlinear solution is visibly *not* a pure cosine — the whole point of
    integrating the real pendulum.
    """
    for name in ("theta0", "amplitude", "angle", "theta"):
        if name in variables:
            a = _finite_or(variables[name], 1.0)
            # Treat a value that looks like degrees (|a| > 2*pi) as degrees.
            a = math.radians(a) if abs(a) > 2.0 * math.pi else a
            return max(-2.7, min(2.7, a)) or 1.0
    return 1.0


def _is_finite(v: float) -> bool:
    return v == v and v not in (float("inf"), float("-inf"))


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - nonlinear pendulum (curated component)."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        ts = {ts}
        ths = {ths}
        rod_len = 2.0
        pivot = np.array([-3.3, 1.4, 0.0])

        title = Text({title}).scale(0.5).to_edge(UP)
        title.set_z_index(5)

        t_tracker = ValueTracker(float(ts[0]))

        def theta_now():
            return float(np.interp(t_tracker.get_value(), ts, ths))

        def bob_point():
            th = theta_now()
            return pivot + rod_len * np.array([np.sin(th), -np.cos(th), 0.0])

        anchor = Dot(pivot, color=GREY_B, radius=0.05)
        rod = always_redraw(lambda: Line(pivot, bob_point(), color=GREY_A, stroke_width=3))
        bob = always_redraw(lambda: Dot(bob_point(), color=YELLOW, radius=0.16))
        trail = TracedPath(bob_point, stroke_color=TEAL, stroke_width=2.5, dissipating_time=1.6)
        trail.set_z_index(1)

        # theta(t) read-out on the right, drawn in sync with the swing.
        axes = Axes(
            x_range=[float(ts[0]), float(ts[-1]), (float(ts[-1]) - float(ts[0])) / 4.0],
            y_range=[-max(abs(min(ths)), abs(max(ths))) * 1.2 - 1e-6,
                     max(abs(min(ths)), abs(max(ths))) * 1.2 + 1e-6,
                     max(abs(min(ths)), abs(max(ths))) / 2.0 + 1e-6],
            x_length=5.0, y_length=3.0,
            axis_config={{"include_tip": False, "stroke_opacity": 0.5}},
        ).to_corner(DR, buff=0.6)
        axes.set_z_index(-5)
        y_label = axes.get_y_axis_label(Text("theta").scale(0.35))
        y_label.set_z_index(5)
        trace_pts = [axes.coords_to_point(t, th) for t, th in zip(ts, ths)]
        trace = VMobject(color=TEAL, stroke_width=3)
        trace.set_points_smoothly(trace_pts)
        trace.set_z_index(0)
        readout = always_redraw(lambda: Dot(
            axes.coords_to_point(t_tracker.get_value(), theta_now()),
            color=YELLOW, radius=0.06))

        self.play(FadeIn(title), Create(axes), FadeIn(y_label), run_time=1.0)
        self.add(anchor, rod, bob, trail)
        self.play(GrowFromCenter(bob), run_time=0.5)
        self.add(readout)
        self.play(
            t_tracker.animate.set_value(float(ts[-1])),
            Create(trace),
            run_time=6.0, rate_func=linear,
        )
        self.wait(0.5)
'''
