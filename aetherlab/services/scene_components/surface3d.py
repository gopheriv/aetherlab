"""Curated component: a rotating 3-D surface of the problem's actual field.

Used when the planner flags needs_3d and no more specific component applies.
Rather than always rendering one generic Gaussian bump, it picks the surface that
matches the problem — a point-charge / potential-well peak, a dipole's +/- pair,
a saddle (unstable equilibrium), a p-orbital's two lobes, or the Gaussian
wave-packet default — so an inherently-3-D problem gets a shape that means
something. Renders a real ThreeDScene (ThreeDAxes + Surface + ambient camera
orbit). Depends only on ``manim`` + ``numpy``.
"""

from __future__ import annotations

from typing import Any

# name -> (z-expression in u, v, r2 ; on-screen label ; keyword stems)
_SURFACES: tuple[tuple[str, str, str, tuple[str, ...]], ...] = (
    ("point_charge",
     "min(1.9 / np.sqrt(r2 + 0.28), 3.0) - 0.5",
     "1/r potential of a point charge",
     ("point charge", "coulomb", "potential well", "electrostatic potential",
      "potential of a", "1/r")),
    ("dipole",
     "1.4 * np.exp(-((u - 1.2) ** 2 + v * v) / 1.1) - 1.4 * np.exp(-((u + 1.2) ** 2 + v * v) / 1.1)",
     "dipole potential (+ and - peaks)",
     ("dipole", "two charges", "electric dipole")),
    ("saddle",
     "0.55 * (u * u - v * v)",
     "saddle: unstable equilibrium",
     ("saddle", "hyperbolic", "unstable equilibrium", "monkey saddle")),
    ("gaussian",
     "1.6 * np.exp(-r2 / 2.5)",
     "Gaussian field",
     ()),  # default
)


def build(class_name: str, solver: Any) -> str | None:
    text = " ".join([
        " ".join(getattr(solver, "keywords", []) or []),
        getattr(solver, "summary", "") or "",
    ]).lower()
    if any(term in text for term in (
        "orbital", "hydrogen", "wavefunction", "wave function",
        "probability density", "p-orbital", "atomic",
    )):
        # A signed heightfield is not a 3D quantum probability-density isosurface.
        return None
    chosen = _SURFACES[-1]
    for surface in _SURFACES[:-1]:
        if any(stem in text for stem in surface[3]):
            chosen = surface
            break
    _name, zexpr, label, _stems = chosen
    title = _shorten(getattr(solver, "summary", "") or "3D field", 54)
    return _TEMPLATE.format(
        class_name=class_name, zexpr=zexpr, label=repr(label), title=repr(title)
    )


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - 3D field surface (curated component)."""

import numpy as np
from manim import *


class {class_name}(ThreeDScene):
    def construct(self):
        title = Text({title}).scale(0.45).to_corner(UL)
        subtitle = Text({label}).scale(0.32).next_to(title, DOWN, aligned_edge=LEFT, buff=0.12)
        self.add_fixed_in_frame_mobjects(title, subtitle)

        axes = ThreeDAxes(
            x_range=[-3, 3, 1], y_range=[-3, 3, 1], z_range=[-2.5, 2.5, 1],
            x_length=6, y_length=6, z_length=4,
        )

        def field(u, v):
            r2 = u * u + v * v
            z = {zexpr}
            return axes.c2p(u, v, float(np.clip(z, -2.4, 2.4)))

        surface = Surface(
            field,
            u_range=[-2.6, 2.6], v_range=[-2.6, 2.6],
            resolution=(30, 30), fill_opacity=0.85,
            checkerboard_colors=[BLUE_D, BLUE_E],
        )

        self.set_camera_orientation(phi=62 * DEGREES, theta=45 * DEGREES, zoom=0.9)
        self.play(Create(axes), run_time=1.0)
        self.play(Create(surface), run_time=2.0)
        self.begin_ambient_camera_rotation(rate=0.35)
        self.wait(3.5)
        self.stop_ambient_camera_rotation()
        self.wait(0.3)
'''
