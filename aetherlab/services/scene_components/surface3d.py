"""Curated component: a rotating 3-D surface for inherently-3-D problems.

Used when the planner flags needs_3d and no exact numeric trajectory applies
(e.g. fields, potentials). Renders a real ThreeDScene with a smooth surface and
an ambient camera orbit. The surface shape is a representative potential/field
bump — a scaffold that reliably renders in 3-D — parameterized only by the
solver title. Depends only on `manim` + `numpy`.
"""

from __future__ import annotations

from typing import Any


def build(class_name: str, solver: Any) -> str | None:
    title = _shorten(getattr(solver, "summary", "") or "3D field", 54)
    return _TEMPLATE.format(class_name=class_name, title=repr(title))


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - 3D surface (curated component)."""

import numpy as np
from manim import *


class {class_name}(ThreeDScene):
    def construct(self):
        title = Text({title}).scale(0.45).to_corner(UL)
        self.add_fixed_in_frame_mobjects(title)

        axes = ThreeDAxes(
            x_range=[-3, 3, 1], y_range=[-3, 3, 1], z_range=[0, 2, 1],
            x_length=6, y_length=6, z_length=3,
        )

        def field(u, v):
            r2 = u * u + v * v
            z = 1.6 * np.exp(-r2 / 2.5)
            return axes.c2p(u, v, z)

        surface = Surface(
            field,
            u_range=[-3, 3], v_range=[-3, 3],
            resolution=(28, 28), fill_opacity=0.85,
            checkerboard_colors=[BLUE_D, BLUE_E],
        )

        self.set_camera_orientation(phi=65 * DEGREES, theta=45 * DEGREES, zoom=0.9)
        self.play(Create(axes), run_time=1.0)
        self.play(Create(surface), run_time=2.0)
        self.begin_ambient_camera_rotation(rate=0.35)
        self.wait(3.5)
        self.stop_ambient_camera_rotation()
        self.wait(0.3)
'''
