"""Curated component: a Kepler orbit with the equal-area law as the hero frame.

Integrates the real two-body gravitational problem — state (x, y, vₓ, v_y) with
r'' = -μ r / |r|³ — through the same scipy / AST-allow-listed path as every other
numeric result, so the planet genuinely moves faster at perihelion and slower at
aphelion. It bakes the trajectory into a self-contained Manim scene: the central
star at the focus, the planet on its ellipse with a comet-tail, a sweeping radius
vector, and two shaded sectors spanning equal *times* — which come out visibly
equal in *area* (Kepler's 2nd law).

Depends only on ``manim`` + ``numpy``. Selected when the solver's domain is an
orbit / Kepler / gravitation problem.
"""

from __future__ import annotations

import math
from typing import Any

_MAX_POINTS = 240
_A = 3.0    # semi-major axis
_MU = 3.0   # GM


def params(solver: Any) -> dict[str, float]:
    """Resolved orbit parameters; shared by build() and explain()."""
    variables = {str(k): v for k, v in dict(getattr(solver, "variables", {}) or {}).items()}
    return {"eccentricity": _clamp(variables.get("eccentricity", variables.get("e", 0.55)), 0.0, 0.85)}


def build(class_name: str, solver: Any) -> str | None:
    """Return a Kepler-orbit scene, or None if it cannot integrate."""
    try:
        import numpy as np
    except Exception:  # noqa: BLE001
        return None

    # Eccentricity comes from the problem when given (0 = circle, →1 = very
    # elongated); the equal-area law reads most clearly around 0.5.
    e = params(solver)["eccentricity"]

    r_a = _A * (1.0 + e)
    v_a = math.sqrt(_MU * (2.0 / r_a - 1.0 / _A))
    period = 2.0 * math.pi * math.sqrt(_A ** 3 / _MU)
    spec = {
        "state": ["x", "y", "vx", "vy"],
        "rhs": ["vx", "vy", "-mu*x/(x*x+y*y)**1.5", "-mu*y/(x*x+y*y)**1.5"],
        "initial": [r_a, 0.0, 0.0, v_a],
        "t_range": [0.0, period],
        "observe": "x",
    }
    try:
        from aetherlab.services.numeric import solve_numeric

        sol = solve_numeric(spec, {"mu": _MU}, max_points=_MAX_POINTS)
    except Exception:  # noqa: BLE001 — composition must never crash the pipeline
        return None
    if not sol.ok or len(sol.t) < 12:
        return None

    xs = np.array(sol.series("x"), dtype=float)
    ys = np.array(sol.series("y"), dtype=float)
    if xs.size != ys.size or not (np.all(np.isfinite(xs)) and np.all(np.isfinite(ys))):
        return None

    # Fit to frame: scale about the focus (origin) then centre the bounding box.
    span_x = float(max(xs.max() - xs.min(), 1e-6))
    span_y = float(max(ys.max() - ys.min(), 1e-6))
    scale = min(8.8 / span_x, 5.0 / span_y)
    cx = 0.5 * (xs.max() + xs.min()) * scale
    cy = 0.5 * (ys.max() + ys.min()) * scale
    shift = np.array([-cx, -cy - 0.3])

    def screen(i: int) -> list[float]:
        return [round(float(xs[i] * scale + shift[0]), 4),
                round(float(ys[i] * scale + shift[1]), 4)]

    path = [screen(i) for i in range(xs.size)]
    star = [round(float(shift[0]), 4), round(float(shift[1]), 4)]

    # Two equal-TIME sectors (equal sample counts) at perihelion and aphelion —
    # equal area by Kepler's 2nd law despite very different arc lengths.
    r = np.hypot(xs, ys)
    peri = int(np.argmin(r))
    apo = int(np.argmax(r))
    span = max(3, xs.size // 12)
    sector_peri = _sector(path, star, peri, span, xs.size)
    sector_apo = _sector(path, star, apo, span, xs.size)

    title = _shorten(getattr(solver, "summary", "") or "Kepler orbit (equal areas)", 60)
    return _TEMPLATE.format(
        class_name=class_name,
        path=repr(path),
        star=repr(star),
        sector_peri=repr(sector_peri),
        sector_apo=repr(sector_apo),
        title=repr(title),
    )


def _clamp(value: Any, lo: float, hi: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        v = lo
    return max(lo, min(hi, v))


def _sector(path: list[list[float]], star: list[float], center: int, span: int, n: int) -> list[list[float]]:
    lo = max(0, center - span // 2)
    hi = min(n - 1, lo + span)
    return [star] + path[lo:hi + 1] + [star]


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


