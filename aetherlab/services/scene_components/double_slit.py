"""Curated component: two-source (double-slit) interference.

Optics/interference had no reliable (non-LLM) visual. This stages two coherent
sources emitting expanding circular wavefronts, and on a screen to the right the
interference intensity I(y) ∝ cos²(π d y / (λ L)) builds up with its bright
fringes marked — Young's experiment as the hero frame.

Deterministic and self-contained (``manim`` + ``numpy`` only). Selected on
double-slit / interference / diffraction phrasing.
"""

from __future__ import annotations

from typing import Any


def params(solver: Any) -> dict[str, float]:
    """Resolved slit geometry; shared by build() and explain()."""
    variables = {str(k): v for k, v in dict(getattr(solver, "variables", {}) or {}).items()}
    # Slit half-separation (scene units) and fringe frequency. Physically the
    # fringe spacing is lambda*L/d, so more separation or shorter wavelength packs
    # more fringes: k_fringe scales with d / lambda.
    gap = _clamp(variables.get("separation", variables.get("slit_separation",
                 variables.get("d", 1.1))), 0.6, 1.8)
    wavelength = _positive(variables.get("wavelength", variables.get("lambda")), 1.0)
    k_fringe = _clamp(1.9 * (gap / 1.1) / wavelength, 1.0, 4.2)
    return {"gap": gap, "wavelength": wavelength, "k_fringe": k_fringe}


def build(class_name: str, solver: Any) -> str | None:
    """Return a double-slit scene; slit spacing & fringe count track the problem."""
    p = params(solver)
    gap, k_fringe = p["gap"], p["k_fringe"]

    title = _shorten(getattr(solver, "summary", "") or "Double-slit interference", 60)
    return _TEMPLATE.format(
        class_name=class_name, gap=repr(round(gap, 4)),
        k_fringe=repr(round(k_fringe, 4)), title=repr(title),
    )


def _positive(value: Any, default: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        return default
    return v if v > 1e-6 else default


def _clamp(value: Any, lo: float, hi: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        v = lo
    return max(lo, min(hi, v))


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - double-slit interference (curated component)."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        title = Text({title}).scale(0.46).to_edge(UP)

        slit_x = -4.6
        gap = {gap}
        top = np.array([slit_x, gap, 0.0])
        bot = np.array([slit_x, -gap, 0.0])

        # Barrier with two slits.
        barrier = VGroup(
            Line([slit_x, 3.2, 0.0], [slit_x, gap + 0.28, 0.0], color=GREY_B, stroke_width=6),
            Line([slit_x, gap - 0.28, 0.0], [slit_x, -gap + 0.28, 0.0], color=GREY_B, stroke_width=6),
            Line([slit_x, -gap - 0.28, 0.0], [slit_x, -3.2, 0.0], color=GREY_B, stroke_width=6),
        )
        s_top = Dot(top, color=YELLOW, radius=0.08)
        s_bot = Dot(bot, color=YELLOW, radius=0.08)

        # Expanding circular wavefronts from each slit.
        r = ValueTracker(0.0)

        def rings(center):
            def make():
                grp = VGroup()
                for i in range(5):
                    rad = r.get_value() - i * 1.15
                    if 0.05 < rad < 9.0:
                        grp.add(Arc(radius=rad, start_angle=-PI / 2.2, angle=PI / 1.1,
                                    arc_center=center, color=TEAL,
                                    stroke_width=2, stroke_opacity=0.6))
                return grp
            return make

        waves_top = always_redraw(rings(top))
        waves_bot = always_redraw(rings(bot))

        # Screen on the right and the interference intensity pattern.
        screen_x = 5.0
        screen = Line([screen_x, 3.2, 0.0], [screen_x, -3.2, 0.0], color=GREY_A, stroke_width=4)
        ys = np.linspace(-3.0, 3.0, 240)
        inten = np.cos({k_fringe} * ys) ** 2
        pattern = VMobject(color=BLUE_C, stroke_width=3)
        pattern.set_points_smoothly(
            [np.array([screen_x - 1.4 * v, y, 0.0]) for y, v in zip(ys, inten)]
        )
        # Bright-fringe markers at the intensity maxima.
        fringes = VGroup(*[
            Dot([screen_x, y, 0.0], color=YELLOW, radius=0.06)
            for y in ys[1:-1][(inten[1:-1] > inten[:-2]) & (inten[1:-1] > inten[2:])]
        ])
        caption = Text("bright where path difference = n*lambda", color=GREY_A).scale(0.28)
        caption.to_edge(DOWN)

        self.play(FadeIn(title), Create(barrier), FadeIn(s_top), FadeIn(s_bot),
                  Create(screen), run_time=1.2)
        self.add(waves_top, waves_bot)
        self.play(r.animate.set_value(11.0), run_time=4.0, rate_func=linear)
        self.play(Create(pattern), run_time=1.4)
        self.play(LaggedStart(*[GrowFromCenter(f) for f in fringes], lag_ratio=0.06),
                  FadeIn(caption), run_time=1.4)
        self.wait(0.5)
'''
