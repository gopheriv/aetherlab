"""Curated component: a phase-space portrait of a 2-state dynamical system.

For an ODE with two state variables (position + velocity), the phase plane
(v vs x) is often the *insight* frame — a damped oscillator spirals into the
origin (the attractor), an undamped one closes into an orbit, an unstable one
winds outward. This bakes the exact integrated (x, v) samples into a Manim scene:
axes, the smooth trajectory as a VMobject, and a tracer dot sweeping along it so
the viewer watches the state evolve toward (or away from) the fixed point.

Driven by the same numeric ground truth as everything else (the solver's
``numeric_spec``, integrated through services/numeric with an AST-allow-listed
RHS). Depends only on ``manim`` + ``numpy``. Returns None unless the spec has
exactly two state variables.
"""

from __future__ import annotations

from typing import Any

_MAX_POINTS = 200


def build(class_name: str, solver: Any) -> str | None:
    """Return a phase-portrait scene for a 2-state numeric spec, or None."""
    spec = getattr(solver, "numeric_spec", None)
    if not isinstance(spec, dict):
        return None
    state = spec.get("state")
    if not (isinstance(state, list) and len(state) == 2):
        return None
    try:
        from aetherlab.services.numeric import solve_numeric

        sol = solve_numeric(spec, getattr(solver, "variables", {}), max_points=_MAX_POINTS)
    except Exception:  # noqa: BLE001 — composition must never crash the pipeline
        return None
    if not sol.ok or len(sol.t) < 3:
        return None

    xname, vname = str(state[0]), str(state[1])
    xs = [round(float(v), 5) for v in sol.series(xname)]
    vs = [round(float(v), 5) for v in sol.series(vname)]
    if len(xs) != len(vs) or len(xs) < 3 or not all(_finite(v) for v in xs + vs):
        return None

    title = _shorten(getattr(solver, "summary", "") or "Phase portrait", 60)
    return _TEMPLATE.format(
        class_name=class_name,
        xs=repr(xs),
        vs=repr(vs),
        xlabel=repr(xname),
        vlabel=repr(vname),
        title=repr(title),
    )


def _finite(v: float) -> bool:
    return v == v and v not in (float("inf"), float("-inf"))


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - phase portrait (curated component)."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        xs = {xs}
        vs = {vs}

        title = Text({title}).scale(0.5).to_edge(UP)

        x_abs = max(abs(min(xs)), abs(max(xs)), 1e-6)
        v_abs = max(abs(min(vs)), abs(max(vs)), 1e-6)
        axes = Axes(
            x_range=[-x_abs * 1.2, x_abs * 1.2, x_abs / 2.0],
            y_range=[-v_abs * 1.2, v_abs * 1.2, v_abs / 2.0],
            x_length=8.0, y_length=5.5,
            axis_config={{"include_tip": True, "stroke_opacity": 0.5}},
        ).to_edge(DOWN)
        x_label = axes.get_x_axis_label(Text({xlabel}).scale(0.4))
        v_label = axes.get_y_axis_label(Text({vlabel}).scale(0.4))

        points = [axes.coords_to_point(x, v) for x, v in zip(xs, vs)]
        curve = VMobject(color=BLUE)
        curve.set_points_smoothly(points)
        start = Dot(points[0], color=TEAL, radius=0.08)
        attractor = Dot(axes.coords_to_point(0.0, 0.0), color=YELLOW, radius=0.07)
        tracer = Dot(points[0], color=YELLOW, radius=0.09)

        self.play(Create(axes), FadeIn(title), FadeIn(x_label), FadeIn(v_label), run_time=1.0)
        self.add(attractor)
        self.play(FadeIn(start), run_time=0.4)
        self.play(Create(curve), run_time=3.5)
        self.add(tracer)
        self.play(MoveAlongPath(tracer, curve), run_time=2.5, rate_func=linear)
        self.wait(0.5)
'''
