"""Curated component: an exact 2-D trajectory animation.

Renders the numerically-integrated solution (ground truth) as a Manim curve
with a tracer dot. The sampled (t, x) data is baked into the generated scene as
plain literals, so the rendered animation is the real solution — not a curve the
LLM guessed — and the scene depends only on `manim` + `numpy`.
"""

from __future__ import annotations

from typing import Any

_MAX_POINTS = 120


def build(class_name: str, solver: Any) -> str | None:
    """Return a complete Manim scene for the solver's numeric trajectory, or None."""
    spec = getattr(solver, "numeric_spec", None)
    if not isinstance(spec, dict):
        return None
    try:
        from aetherlab.services.numeric import solve_numeric

        sol = solve_numeric(spec, getattr(solver, "variables", {}), max_points=_MAX_POINTS)
    except Exception:
        return None
    if not sol.ok or len(sol.t) < 2:
        return None

    xs = [round(float(v), 5) for v in sol.t]
    ys = [round(float(v), 5) for v in sol.series()]
    if len(xs) != len(ys) or not all(_finite(v) for v in xs + ys):
        return None

    title = _shorten(getattr(solver, "summary", "") or "Numerical solution", 60)
    ylabel = sol.observe or "x"
    return _TEMPLATE.format(
        class_name=class_name,
        xs=repr(xs),
        ys=repr(ys),
        title=repr(title),
        ylabel=repr(ylabel),
    )


def _finite(v: float) -> bool:
    return v == v and v not in (float("inf"), float("-inf"))


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - numeric trajectory (curated component)."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        xs = {xs}
        ys = {ys}

        title = Text({title}).scale(0.5).to_edge(UP)

        x_min, x_max = min(xs), max(xs)
        y_min, y_max = min(ys), max(ys)
        if y_max - y_min < 1e-9:
            y_min, y_max = y_min - 1.0, y_max + 1.0
        y_pad = (y_max - y_min) * 0.15

        axes = Axes(
            x_range=[x_min, x_max, (x_max - x_min) / 6.0],
            y_range=[y_min - y_pad, y_max + y_pad, (y_max - y_min) / 4.0],
            x_length=10,
            y_length=5,
            axis_config={{"include_tip": False}},
        ).to_edge(DOWN)
        x_label = axes.get_x_axis_label(Text("t").scale(0.4))
        y_label = axes.get_y_axis_label(Text({ylabel}).scale(0.4))

        points = [axes.coords_to_point(x, y) for x, y in zip(xs, ys)]
        curve = VMobject(color=BLUE)
        curve.set_points_smoothly(points)
        tracer = Dot(points[0], color=YELLOW, radius=0.07)

        self.play(Create(axes), FadeIn(title), FadeIn(x_label), FadeIn(y_label), run_time=1.0)
        self.play(Create(curve), run_time=3.0)
        self.add(tracer)
        self.play(MoveAlongPath(tracer, curve), run_time=2.5)
        self.wait(0.5)
'''
