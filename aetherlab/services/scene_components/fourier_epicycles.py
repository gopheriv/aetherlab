"""Curated component: a Fourier series built from rotating vectors (epicycles).

The "series / transforms" domain had no reliable (non-LLM) visual. This is the
canonical 3Blue1Brown-style construction: a chain of phasors — one per odd
harmonic, rotating at frequency k with amplitude 4/(πk) — summed tip-to-tail, so
the tip traces the epicycle drawing while its height simultaneously builds a
square wave on a time axis to the right. It makes concrete that a Fourier series
*is* a sum of rotating vectors.

Fully parametric (no baked data) and deterministic — depends only on ``manim`` +
``numpy`` + ``math``. Selected when the prompt is about Fourier series /
epicycles / a square wave.
"""

from __future__ import annotations

from typing import Any


def params(solver: Any) -> dict[str, Any]:
    """Resolved harmonic list; shared by build() and explain()."""
    variables = {str(k): v for k, v in dict(getattr(solver, "variables", {}) or {}).items()}
    terms = variables.get("terms", variables.get("n_terms",
            variables.get("harmonics", variables.get("num_terms", 5))))
    try:
        terms = int(round(float(terms)))
    except (TypeError, ValueError):
        terms = 5
    terms = max(2, min(9, terms))
    # First `terms` odd harmonics — the square-wave partial sum.
    return {"harmonics": [2 * i + 1 for i in range(terms)]}


def build(class_name: str, solver: Any) -> str | None:
    """Return a rotating-phasor Fourier scene; term count tracks the problem."""
    harmonics = params(solver)["harmonics"]

    title = _shorten(getattr(solver, "summary", "") or "Fourier series: rotating vectors", 60)
    return _TEMPLATE.format(
        class_name=class_name,
        harmonics=repr(harmonics),
        title=repr(title),
    )


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - Fourier epicycles (curated component)."""

import math

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        harmonics = {harmonics}
        amps = [4.0 / (math.pi * k) for k in harmonics]
        center = np.array([-3.6, 0.0, 0.0])

        title = Text({title}).scale(0.46).to_edge(UP)

        def chain(tt):
            group = VGroup()
            p = center.copy()
            for k, a in zip(harmonics, amps):
                ang = k * tt
                nxt = p + a * np.array([math.cos(ang), math.sin(ang), 0.0])
                group.add(Circle(radius=a, color=GREY_B, stroke_width=1.5, stroke_opacity=0.35).move_to(p))
                group.add(Line(p, nxt, color=YELLOW, stroke_width=2.5))
                p = nxt
            return group, p

        def tip(tt):
            return chain(tt)[1]

        def wave_value(tt):
            return float(sum(a * math.sin(k * tt) for k, a in zip(harmonics, amps)))

        axes = Axes(
            x_range=[0.0, 2.0 * math.pi, math.pi / 2.0],
            y_range=[-1.4, 1.4, 0.5],
            x_length=5.5, y_length=3.2,
            axis_config={{"include_tip": False, "stroke_opacity": 0.5}},
        ).shift(RIGHT * 2.4)
        target = axes.plot(lambda x: sum(a * math.sin(k * x) for k, a in zip(harmonics, amps)),
                           x_range=[0.0, 2.0 * math.pi], color=BLUE_C)

        t = ValueTracker(0.0)
        phasors = always_redraw(lambda: chain(t.get_value())[0])
        pen = always_redraw(lambda: Dot(tip(t.get_value()), color=YELLOW, radius=0.05))
        drawing = TracedPath(lambda: tip(t.get_value()), stroke_color=TEAL, stroke_width=2.5)
        wave_dot = always_redraw(lambda: Dot(
            axes.c2p(t.get_value(), wave_value(t.get_value())), color=YELLOW, radius=0.06))
        link = always_redraw(lambda: DashedLine(
            tip(t.get_value()),
            axes.c2p(t.get_value(), wave_value(t.get_value())),
            color=GREY_B, stroke_width=1.5, dash_length=0.08))

        self.play(FadeIn(title), Create(axes), run_time=1.0)
        self.add(phasors, drawing, pen, link, wave_dot)
        self.play(t.animate.set_value(2.0 * math.pi), Create(target),
                  run_time=8.0, rate_func=linear)
        self.wait(0.5)
'''
