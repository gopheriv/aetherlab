"""Scenario: two waves meet.

Three rows on one string. On top a wave travels right; in the middle an
identical wave travels left; at the bottom is their sum. The sum does not
travel. It breathes in place, and the dashed node lines show that at those
points the two travelling waves are always equal and opposite. At the end the
scene pauses at the instant the two waves cancel everywhere: the string is
momentarily flat, yet it keeps moving.

Mode number comes from ``standing_wave.params``, so it is the same mode the
component draws: y = A·sin(kx - ωt) + A·sin(kx + ωt) = 2A·sin(kx)·cos(ωt), k = nπ/L.
"""

from __future__ import annotations

from typing import Any


def build(class_name: str, solver: Any) -> str | None:
    from aetherlab.services.scene_components import standing_wave

    n = standing_wave.params(solver)["mode"]
    return _TEMPLATE.format(class_name=class_name, n=n)


def explain(solver: Any) -> dict[str, Any] | None:
    from aetherlab.services.scene_components import standing_wave

    n = standing_wave.params(solver)["mode"]
    return {
        "heading": "Two waves meet",
        "equation": "A·sin(kx - ωt) + A·sin(kx + ωt) = 2A·sin(kx)·cos(ωt)",
        "watch": "a right-moving wave (top) and a left-moving wave (middle) add up to the bottom row.",
        "facts": [
            f"Mode n = {n}: {n + 1} nodes (including the ends), where the two waves always cancel",
            f"Wavelength λ = 2L/n = {2.0 / n:.2f}·L",
            "Once per half cycle the two waves cancel everywhere and the string is flat",
        ],
        "takeaway": "A standing wave is two equal waves travelling in opposite directions. Neither stops; their sum just stops travelling.",
    }


_TEMPLATE = '''\
"""Generated by AetherLab - scenario: two waves meet."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        n = {n}
        x0, length = -5.4, 10.8
        k = n * PI / length
        amp = 0.55
        rows = {{"right": 2.05, "left": 0.35, "sum": -1.95}}
        phase = ValueTracker(0.0)
        xs = np.linspace(x0, x0 + length, 220)

        def curve(kind, y0, color):
            def draw():
                w = phase.get_value()
                u = k * (xs - x0)
                if kind == "right":
                    ys = amp * np.sin(u - w)
                elif kind == "left":
                    ys = amp * np.sin(u + w)
                else:
                    ys = amp * (np.sin(u - w) + np.sin(u + w))
                line = VMobject(color=color, stroke_width=4)
                line.set_points_as_corners([np.array([x, y0 + y, 0.0]) for x, y in zip(xs, ys)])
                return line
            return always_redraw(draw)

        title = Text("Two waves meet", font_size=34, color=YELLOW).to_edge(UP, buff=0.25)
        axes = VGroup(*[
            Line([x0, y, 0], [x0 + length, y, 0], color=GREY_D, stroke_width=1.5)
            for y in rows.values()
        ])
        right = curve("right", rows["right"], BLUE)
        left = curve("left", rows["left"], RED)
        total = curve("sum", rows["sum"], TEAL)
        tag_r = Text("travels right", font_size=24, color=BLUE).move_to([5.3, rows["right"] + 0.85, 0])
        tag_l = Text("travels left", font_size=24, color=RED).move_to([5.3, rows["left"] + 0.85, 0])
        tag_s = Text("sum: stands still", font_size=24, color=TEAL).move_to([5.0, rows["sum"] + 1.35, 0])
        arrow_r = Arrow([3.9, rows["right"] + 0.85, 0], [4.5, rows["right"] + 0.85, 0], color=BLUE, buff=0)
        arrow_l = Arrow([4.5, rows["left"] + 0.85, 0], [3.9, rows["left"] + 0.85, 0], color=RED, buff=0)
        plus = Text("+", font_size=40, color=GREY_B).move_to([x0 - 0.45, (rows["right"] + rows["left"]) / 2, 0])
        equals = Text("=", font_size=40, color=GREY_B).move_to([x0 - 0.45, (rows["left"] + rows["sum"]) / 2, 0])

        node_xs = [x0 + length * j / n for j in range(n + 1)]
        nodes = VGroup(*[
            DashedLine([x, rows["right"] + 0.75, 0], [x, rows["sum"] - 1.25, 0],
                       color=GREY_B, stroke_width=1.5, dash_length=0.1)
            for x in node_xs
        ])
        node_dots = VGroup(*[Dot([x, rows["sum"], 0], color=RED, radius=0.08) for x in node_xs])
        node_tag = Text("nodes: the two waves always cancel here", font_size=24,
                        color=GREY_A).move_to([0, rows["sum"] - 1.55, 0])

        self.play(FadeIn(title), Create(axes), run_time=0.8)
        # The right-moving wave on its own, then the left-moving one.
        self.play(FadeIn(right), FadeIn(tag_r), GrowArrow(arrow_r), run_time=0.6)
        self.play(phase.animate.set_value(PI), run_time=1.6, rate_func=linear)
        self.play(FadeIn(left), FadeIn(tag_l), GrowArrow(arrow_l), FadeIn(plus), run_time=0.6)
        self.play(phase.animate.set_value(2 * PI), run_time=1.6, rate_func=linear)
        # Their sum, which does not travel.
        self.play(FadeIn(total), FadeIn(tag_s), FadeIn(equals), run_time=0.6)
        self.play(phase.animate.set_value(4 * PI), run_time=3.2, rate_func=linear)
        self.play(Create(nodes), GrowFromCenter(node_dots), FadeIn(node_tag), run_time=1.0)
        self.play(phase.animate.set_value(6 * PI + PI / 2), run_time=3.6, rate_func=linear)
        # Freeze at the instant the waves cancel everywhere: the sum is flat.
        flat = Text("right now they cancel everywhere: the string is flat, yet still moving",
                    font_size=24, color=YELLOW_A).move_to(node_tag)
        self.play(Indicate(total, color=YELLOW), FadeOut(node_tag), FadeIn(flat), run_time=1.0)
        self.wait(1.2)
'''
