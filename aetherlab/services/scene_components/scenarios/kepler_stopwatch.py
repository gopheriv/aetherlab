"""Scenario: Kepler's stopwatch.

A stopwatch ticks 12 times per orbit. At every tick the planet leaves behind the
wedge it swept since the last tick. Near the star the wedges are short and fat;
far away they are long and thin. Two bar charts fill in beside the orbit as the
ticks pass. "Distance travelled per tick" varies several-fold, while "area swept
per tick" stays flat. That flat row of bars is Kepler's second law.

The orbit is the component's two-body integration (``orbit.params`` and the same
constants). ``solve_numeric`` samples at uniform times, so equal sample counts
are equal times. Distances and areas are measured from those samples.
"""

from __future__ import annotations

import math
from typing import Any

_TICKS = 12
_PER_TICK = 20
_SWEEP_S = 11.0


def _orbit_samples(solver: Any) -> dict[str, Any] | None:
    import numpy as np

    from aetherlab.services.numeric import solve_numeric
    from aetherlab.services.scene_components import orbit

    e = orbit.params(solver)["eccentricity"]
    a, mu = orbit._A, orbit._MU
    r_a = a * (1.0 + e)
    v_a = math.sqrt(mu * (2.0 / r_a - 1.0 / a))
    period = 2.0 * math.pi * math.sqrt(a ** 3 / mu)
    n = _TICKS * _PER_TICK + 1
    sol = solve_numeric({
        "state": ["x", "y", "vx", "vy"],
        "rhs": ["vx", "vy", "-mu*x/(x*x+y*y)**1.5", "-mu*y/(x*x+y*y)**1.5"],
        "initial": [r_a, 0.0, 0.0, v_a],
        "t_range": [0.0, period],
        "observe": "x",
    }, {"mu": mu}, max_points=n)
    if not sol.ok or len(sol.t) != n:
        return None
    xs = np.array(sol.series("x"), dtype=float)
    ys = np.array(sol.series("y"), dtype=float)
    if not (np.all(np.isfinite(xs)) and np.all(np.isfinite(ys))):
        return None
    dist, area = [], []
    for k in range(_TICKS):
        i0, i1 = k * _PER_TICK, (k + 1) * _PER_TICK
        px, py = xs[i0:i1 + 1], ys[i0:i1 + 1]
        dist.append(float(np.sum(np.hypot(np.diff(px), np.diff(py)))))
        # wedge (star at the origin + arc): shoelace area
        wx = np.concatenate([[0.0], px, [0.0]])
        wy = np.concatenate([[0.0], py, [0.0]])
        area.append(0.5 * abs(float(np.dot(wx[:-1], wy[1:]) - np.dot(wx[1:], wy[:-1]))))
    return {"e": e, "xs": xs, "ys": ys, "dist": dist, "area": area}


def build(class_name: str, solver: Any) -> str | None:
    data = _orbit_samples(solver)
    if data is None:
        return None
    xs, ys = data["xs"], data["ys"]
    # Fit the orbit into the left half of the frame, star (focus) at the origin.
    span_x = float(xs.max() - xs.min())
    span_y = float(ys.max() - ys.min())
    scale = min(6.0 / span_x, 5.4 / span_y)
    cx = -3.3 - 0.5 * (xs.max() + xs.min()) * scale
    cy = -0.35 - 0.5 * (ys.max() + ys.min()) * scale
    path = [[round(float(x * scale + cx), 4), round(float(y * scale + cy), 4)] for x, y in zip(xs, ys)]
    star = [round(cx, 4), round(cy, 4)]
    d_max, a_max = max(data["dist"]), max(data["area"])
    dist_h = [round(1.6 * d / d_max, 4) for d in data["dist"]]
    area_h = [round(1.6 * a / a_max, 4) for a in data["area"]]
    spread = 100.0 * (max(data["area"]) - min(data["area"])) / (sum(data["area"]) / _TICKS)
    return _TEMPLATE.format(
        class_name=class_name, path=repr(path), star=repr(star),
        dist_h=repr(dist_h), area_h=repr(area_h),
        ticks=_TICKS, per_tick=_PER_TICK, sweep_s=_SWEEP_S,
        dist_label=repr(f"distance per tick: fastest / slowest = {d_max / min(data['dist']):.1f}×"),
        area_label=repr(f"area per tick: all equal (within {spread:.1f}%)"),
    )


def explain(solver: Any) -> dict[str, Any] | None:
    data = _orbit_samples(solver)
    if data is None:
        return None
    dist, area = data["dist"], data["area"]
    share = 100.0 / _TICKS
    spread = 100.0 * (max(area) - min(area)) / (sum(area) / _TICKS)
    return {
        "heading": "Kepler's stopwatch",
        "equation": "dA/dt = L / (2m) = constant",
        "watch": f"every 1/{_TICKS} of an orbit the planet leaves a wedge behind; compare the two bar charts.",
        "facts": [
            f"Orbit eccentricity e = {data['e']:.2f}",
            f"Distance per tick varies {max(dist) / min(dist):.1f}× between the slowest and fastest ticks",
            f"Area per tick: each wedge is {share:.1f}% of the ellipse, equal within {spread:.1f}%",
        ],
        "takeaway": "The planet speeds up near the star and slows far away, but it always sweeps equal areas in equal times.",
    }


