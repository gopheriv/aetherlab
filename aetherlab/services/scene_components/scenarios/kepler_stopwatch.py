        done = VGroup()

        def settle(group):
            # When a tick completes, freeze its wedge and add its two bars.
            k = len(group) // 4
            if k < ticks and idx.get_value() >= (k + 1) * per_tick:
                x = 1.0 + (k + 0.5) * bar_w
                c = colors[k % 2]
                group.add(wedge(k, 0.45))
                group.add(Dot(pts[(k + 1) * per_tick], color=c, radius=0.05))
                group.add(Rectangle(width=bar_w * 0.8, height=dist_h[k], fill_color=c,
                                    fill_opacity=0.85, stroke_width=0).move_to(
                                    [x, 0.75 + dist_h[k] / 2, 0]))
                group.add(Rectangle(width=bar_w * 0.8, height=area_h[k], fill_color=c,
                                    fill_opacity=0.85, stroke_width=0).move_to(
                                    [x, -2.45 + area_h[k] / 2, 0]))

        done.add_updater(settle)

        self.play(FadeIn(title), Create(orbit), FadeIn(glow), GrowFromCenter(star), run_time=1.2)
        self.play(FadeIn(dist_chart), FadeIn(area_chart), run_time=0.6)
        self.add(done, current, radius, planet)
        self.play(idx.animate.set_value(float(len(pts) - 1)), run_time={sweep_s}, rate_func=linear)
        done.clear_updaters()
        current.clear_updaters()
        self.remove(current)
        dist_note = Text({dist_label}, font_size=22, color=ORANGE).move_to([3.85, 2.75, 0])
        area_note = Text({area_label}, font_size=22, color=GREEN_B).move_to([3.85, -0.45, 0])
        self.play(FadeIn(dist_note), FadeIn(area_note), run_time=0.8)
        self.wait(1.5)
