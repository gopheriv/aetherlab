"""Scenario: the pendulum race.

Race 1: a 1 kg bob and a 3 kg bob on equal strings, next to a 1 kg bob on a
string twice as long, released together. The first two stay in perfect step,
because the equation of motion contains no mass. The long one falls behind by
exactly √2. Race 2: the same pendulum released from 10° and from 60°. The wide
swing drifts behind, because large swings are slower than the small-angle
formula.

Every angle comes from ``solve_numeric`` on the component's nonlinear ODE with
the component's own parameters. The swing counters count real zero crossings,
baked in as times.
"""

from __future__ import annotations

import math
from typing import Any

_RACE1_S = 7.0          # physics seconds shown in race 1 (played 1:1)
_RACE2_S = 6.5
_RACE1_ANGLE = 0.5      # rad (~29°): wide enough to see, same for all three
_SMALL, _BIG = math.radians(10.0), math.radians(60.0)
_POINTS = 420


def _solve(theta0: float, length: float, p: dict[str, float], t_end: float):
    from aetherlab.services.numeric import solve_numeric
    from aetherlab.services.scene_components import pendulum

    spec = dict(pendulum.numeric_spec(theta0), t_range=[0.0, t_end])
    return solve_numeric(
        spec, {"gravity": p["gravity"], "length": length, "damping": p["damping"]},
        max_points=_POINTS,
    )


def _crossings(ts: list[float], ys: list[float]) -> list[float]:
    out = []
    for i in range(1, len(ys)):
        if (ys[i - 1] < 0.0) != (ys[i] < 0.0) and ys[i] != ys[i - 1]:
            frac = -ys[i - 1] / (ys[i] - ys[i - 1])
            out.append(round(ts[i - 1] + frac * (ts[i] - ts[i - 1]), 4))
    return out


def _first_period(crossings: list[float]) -> float | None:
    return crossings[2] - crossings[0] if len(crossings) >= 3 else None


def _race(solver: Any) -> dict[str, Any] | None:
    from aetherlab.services.scene_components import pendulum

    p = pendulum.params(solver)
    length = p["length"]
    runs = {
        "short": _solve(_RACE1_ANGLE, length, p, _RACE1_S),
        "long": _solve(_RACE1_ANGLE, 2.0 * length, p, _RACE1_S),
        "small": _solve(_SMALL, length, p, _RACE2_S),
        "big": _solve(_BIG, length, p, _RACE2_S),
    }
    if not all(run.ok and len(run.t) > 10 for run in runs.values()):
        return None
    data: dict[str, Any] = {"params": p}
    for key, run in runs.items():
        ts = [round(float(v), 4) for v in run.t]
        ths = [round(float(v), 5) for v in run.series("theta")]
        if not all(math.isfinite(v) for v in ts + ths):
            return None
        data[key] = (ts, ths, _crossings(ts, ths))
    return data


def build(class_name: str, solver: Any) -> str | None:
    race = _race(solver)
    if race is None:
        return None
    periods = {k: _first_period(race[k][2]) for k in ("short", "long", "small", "big")}
    if any(v is None for v in periods.values()):
        return None
    ratio = periods["long"] / periods["short"]
    return _TEMPLATE.format(
        class_name=class_name,
        t1=repr(race["short"][0]), short=repr(race["short"][1]), long=repr(race["long"][1]),
        c_short=repr(race["short"][2]), c_long=repr(race["long"][2]),
        t2=repr(race["small"][0]), small=repr(race["small"][1]), big=repr(race["big"][1]),
        c_small=repr(race["small"][2]), c_big=repr(race["big"][2]),
        race1_s=_RACE1_S, race2_s=_RACE2_S,
        verdict1=repr(f"Equal strings: perfect step, mass or not.   Double length: {ratio:.2f}× slower"),
        verdict2=repr(
            f"60° swing: {periods['big']:.2f} s   vs   10° swing: {periods['small']:.2f} s"
            "  - wide swings are slower"
        ),
    )


def explain(solver: Any) -> dict[str, Any] | None:
    race = _race(solver)
    if race is None:
        return None
    t = {k: _first_period(race[k][2]) for k in ("short", "long", "small", "big")}
    if any(v is None for v in t.values()):
        return None
    length = race["params"]["length"]
    return {
        "heading": "The pendulum race",
        "equation": "θ'' = -(g/L)·sin θ   (no mass anywhere)",
        "watch": "a 1 kg and a 3 kg bob on equal strings race a pendulum twice as long.",
        "facts": [
            f"1 kg and 3 kg on {length:.2f} m strings: same period, {t['short']:.2f} s",
            f"Twice the length: {t['long']:.2f} s, √2 = {t['long'] / t['short']:.2f}× slower",
            f"From 10°: {t['small']:.2f} s.  From 60°: {t['big']:.2f} s",
        ],
        "takeaway": "Length and gravity set the rhythm; mass never does. Wide swings run a little slow.",
    }


