"""Scenario: energy buckets.

Act 1 shows the two special motions of two coupled masses side by side: moving
together (slow, ω₁) and moving opposite (fast, ω₂). Act 2 pushes only the left
mass. Under each mass an energy bar (a bucket) fills and drains, and the energy
visibly pours from the left bucket into the right and back. The scene pauses at
the moment the left mass has handed over almost all of its energy.

Mode frequencies come from ``coupled_oscillators.params`` (ω₁ = √(k/m),
ω₂ = √(3k/m)). The act-2 motion and both energy bars come from ``solve_numeric``
on the component's equations of motion.
"""

from __future__ import annotations

import math
from typing import Any

_POINTS = 400


def _run(solver: Any) -> dict[str, Any] | None:
    from aetherlab.services.numeric import solve_numeric
    from aetherlab.services.scene_components import coupled_oscillators

    p = coupled_oscillators.params(solver)
    k, m = p["stiffness"], p["mass"]
    w1, w2 = math.sqrt(k / m), math.sqrt(3.0 * k / m)
    transfer = math.pi / (w2 - w1)
    t_end = 2.2 * transfer
    sol = solve_numeric({
        "state": ["x1", "x2", "v1", "v2"],
        "rhs": ["v1", "v2", "(-2*k*x1 + k*x2)/m", "(k*x1 - 2*k*x2)/m"],
        "initial": [1.0, 0.0, 0.0, 0.0],
        "t_range": [0.0, t_end],
        "observe": "x1",
    }, {"k": k, "m": m}, max_points=_POINTS)
    if not sol.ok:
        return None
    x1, x2 = list(sol.series("x1")), list(sol.series("x2"))
    v1, v2 = list(sol.series("v1")), list(sol.series("v2"))
    total = k  # ½k·1² in the wall spring + ½k·1² in the middle spring at t = 0
    e1 = [(0.5 * m * a ** 2 + 0.5 * k * b ** 2) / total for a, b in zip(v1, x1)]
    e2 = [(0.5 * m * a ** 2 + 0.5 * k * b ** 2) / total for a, b in zip(v2, x2)]
    if not all(math.isfinite(v) for v in x1 + x2 + e1 + e2):
        return None
    # the moment the right bucket is fullest during the first exchange
    first = [i for i, t in enumerate(sol.t) if t <= 1.5 * transfer]
    peak = max(first, key=lambda i: e2[i])
    return {
        "w1": w1, "w2": w2, "transfer": transfer, "t_end": t_end,
        "ts": [round(float(t), 4) for t in sol.t],
        "x1": [round(v, 5) for v in x1], "x2": [round(v, 5) for v in x2],
        "e1": [round(v, 5) for v in e1], "e2": [round(v, 5) for v in e2],
        "peak_t": float(sol.t[peak]), "peak_share": e2[peak] / max(e1[peak] + e2[peak], 1e-9),
    }


def build(class_name: str, solver: Any) -> str | None:
    run = _run(solver)
    if run is None:
        return None
    # play act 2 at a speed that fits ~10 s of video
    speed = max(1.0, run["t_end"] / 10.0)
    return _TEMPLATE.format(
        class_name=class_name,
        ts=repr(run["ts"]), x1=repr(run["x1"]), x2=repr(run["x2"]),
        e1=repr(run["e1"]), e2=repr(run["e2"]),
        w1=round(run["w1"], 4), w2=round(run["w2"], 4),
        peak_t=round(run["peak_t"], 4), t_end=round(run["t_end"], 4),
        run1=round(run["peak_t"] / speed, 2), run2=round((run["t_end"] - run["peak_t"]) / speed, 2),
        peak_note=repr(f"t = {run['peak_t']:.1f} s: the right mass holds "
                       f"{100 * run['peak_share']:.0f}% of the moving energy"),
        w1_label=repr(f"together: ω₁ = {run['w1']:.2f} rad/s"),
        w2_label=repr(f"opposite: ω₂ = {run['w2']:.2f} rad/s"),
    )


def explain(solver: Any) -> dict[str, Any] | None:
    run = _run(solver)
    if run is None:
        return None
    return {
        "heading": "Energy buckets",
        "equation": "m·x₁'' = -2k·x₁ + k·x₂,   m·x₂'' = k·x₁ - 2k·x₂",
        "watch": "first the two special motions, then the energy pouring between the buckets.",
        "facts": [
            f"Moving together: ω₁ = √(k/m) = {run['w1']:.2f} rad/s",
            f"Moving opposite: ω₂ = √(3k/m) = {run['w2']:.2f} rad/s",
            f"Push one mass: after {run['peak_t']:.1f} s the other holds "
            f"{100 * run['peak_share']:.0f}% of the energy",
        ],
        "takeaway": "Pushing one mass starts both special motions at once. They drift in and out of step, and the energy sloshes between the masses.",
    }


