"""Scenario: a square wave, one circle at a time.

The component draws the whole partial sum at once. Here the circles arrive one
by one. Each round, one more rotating circle joins the chain, and its tip draws
the new partial sum over a ghost of the previous round. The target square wave
waits as a dashed outline. A readout gives the overshoot at the corner for each
round. It shrinks at first and then stalls near 9% (the Gibbs phenomenon), even
as the rest of the curve sharpens.

Harmonic count comes from ``fourier_epicycles.params``. Overshoots are measured
numerically from each partial sum.
"""

from __future__ import annotations

import math
from typing import Any


def _overshoots(harmonics: list[int]) -> list[float]:
    """Corner overshoot (% of the jump) of each partial sum, measured on a fine grid."""
    import numpy as np

    x = np.linspace(1e-4, math.pi / 2, 20000)
    out = []
    total = np.zeros_like(x)
    for n in harmonics:
        total = total + (4.0 / math.pi) * np.sin(n * x) / n
        out.append(round(100.0 * (float(total.max()) - 1.0) / 2.0, 1))
    return out


def build(class_name: str, solver: Any) -> str | None:
    from aetherlab.services.scene_components import fourier_epicycles

    harmonics = fourier_epicycles.params(solver)["harmonics"]
    # Rounds are written out (not looped) so the static duration estimate that
    # sizes the explanation cards counts every round.
    round_lines: list[str] = []
    for k in range(1, len(harmonics) + 1):
        round_lines += [
            f"        count[0] = {k}",
            "        t.set_value(0.0)",
            "        self.play(t.animate.set_value(2 * PI), run_time=2.3, rate_func=linear)",
            "        ghosts.add(trace().set_stroke(color=BLUE_D, opacity=0.35, width=2))",
            "        self.wait(0.3)",
        ]
    rounds = "\n".join(round_lines)
    peak_x = math.pi / (harmonics[-1] + 1)
    return _TEMPLATE.format(
        class_name=class_name, harmonics=repr(harmonics),
        overshoots=repr(_overshoots(harmonics)), rounds=rounds, peak_x=round(peak_x, 4),
    )


def explain(solver: Any) -> dict[str, Any] | None:
    from aetherlab.services.scene_components import fourier_epicycles

    harmonics = fourier_epicycles.params(solver)["harmonics"]
    over = _overshoots(harmonics)
    return {
        "heading": "A square wave, one circle at a time",
        "equation": "f(x) = (4/π)·Σ sin(n·x)/n,   n = 1, 3, 5, ...",
        "watch": "each round adds one rotating circle; the new curve is drawn over the last one's ghost.",
        "facts": [
            f"{len(harmonics)} rounds, adding harmonics n = {', '.join(str(h) for h in harmonics)}",
            f"Corner overshoot per round: {', '.join(f'{v:.1f}%' for v in over)}",
            "The overshoot stalls near 9% of the jump: the Gibbs phenomenon",
        ],
        "takeaway": "Each circle adds finer detail, and the curve approaches the square wave everywhere except right at the jumps.",
    }


