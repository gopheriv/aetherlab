"""Scenario: photon by photon.

Light is sent through the two slits one photon at a time. Each photon lands at a
single random spot, and nothing about one hit looks like a wave. As hundreds
accumulate, a histogram beside the screen grows into bright and dark bands.
Then one slit is covered and the build-up repeats: the bands vanish into a
single broad hump, because there is no longer a second path to interfere with.

Photons are not drawn going through a particular slit; that picture would teach
a misconception. Hit positions are sampled (fixed seed) from the intensity the
component uses, I(y) ∝ cos²(k·y) under a single-slit envelope sinc²(y/b), and
from the envelope alone once one slit is covered. The band spacing follows
``double_slit.params``.
"""

from __future__ import annotations

import math
from typing import Any

_TWO_SLIT_HITS = 520
_ONE_SLIT_HITS = 420
_ENVELOPE_B = 3.4      # first zero of the single-slit envelope (scene units)
_SCREEN_HALF = 3.0


def _sample(k_fringe: float, two_slits: bool, count: int, seed: int) -> list[list[float]]:
    import numpy as np

    rng = np.random.default_rng(seed)
    out: list[list[float]] = []
    while len(out) < count:
        y = rng.uniform(-_SCREEN_HALF, _SCREEN_HALF, 4000)
        weight = np.sinc(y / _ENVELOPE_B) ** 2
        if two_slits:
            weight = weight * np.cos(k_fringe * y) ** 2
        keep = rng.uniform(0.0, 1.0, y.size) < weight
        jitter = rng.uniform(-0.1, 0.1, y.size)
        out.extend([[round(float(j), 3), round(float(v), 3)] for v, j in zip(y[keep], jitter[keep])])
    return out[:count]


def build(class_name: str, solver: Any) -> str | None:
    from aetherlab.services.scene_components import double_slit

    p = double_slit.params(solver)
    two = _sample(p["k_fringe"], True, _TWO_SLIT_HITS, 2026)
    one = _sample(p["k_fringe"], False, _ONE_SLIT_HITS, 926)
    # The first photons are written out (not looped) so the static duration
    # estimate that sizes the explanation cards counts each one.
    single_lines: list[str] = []
    for i in range(5):
        single_lines += [
            f"        first.add(Dot(hit_point(two[{i}]), color=YELLOW, radius=0.045))",
            "        self.play(Flash(source, color=YELLOW, line_length=0.18, flash_radius=0.25),",
            f"                  FadeIn(first[{i}], scale=4), run_time=0.55)",
        ]
    singles = "\n".join(single_lines)
    return _TEMPLATE.format(
        class_name=class_name, two=repr(two), one=repr(one),
        half_gap=round(min(0.6 * p["gap"], 1.0), 4), singles=singles,
    )


def explain(solver: Any) -> dict[str, Any] | None:
    from aetherlab.services.scene_components import double_slit

    p = double_slit.params(solver)
    spacing = math.pi / p["k_fringe"]
    return {
        "heading": "Photon by photon",
        "equation": "I(y) ∝ cos²(π·d·y / (λ·L))   (two slits open)",
        "watch": "single photons land one at a time; watch the histogram on the right.",
        "facts": [
            f"{_TWO_SLIT_HITS} photons with both slits open; bright bands {spacing:.2f} units apart",
            "Each photon lands at one spot: no single hit shows a wave",
            f"Then one slit is covered: {_ONE_SLIT_HITS} photons build one broad hump, no bands",
        ],
        "takeaway": "Bands need two open paths. Even one photon at a time, its wave goes through both slits and interferes with itself.",
    }


