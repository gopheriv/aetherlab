"""Curated component: concave-mirror image formation by ray tracing.

The reflective counterpart to the thin lens. For a concave mirror (focal length
f, centre of curvature C = 2f), an object beyond C forms a real, inverted,
diminished image between F and C. This draws the textbook ray diagram: the
mirror arc, the optical axis, F and C marked, the object, the three principal
rays (parallel→through F, through F→parallel, through C→back on itself), and the
image where they reconverge — placed by the mirror equation 1/f = 1/do + 1/di.

Deterministic and self-contained (``manim`` + ``numpy`` only). Selected on
mirror / concave / reflection / curved-mirror phrasing.
"""

from __future__ import annotations

from typing import Any


def params(solver: Any) -> dict[str, float]:
    """Resolved mirror geometry; shared by build() and explain()."""
    variables = {str(k): float(v) for k, v in dict(getattr(solver, "variables", {}) or {}).items()
                 if _is_num(v)}
    f = _clamp(variables.get("focal_length", variables.get("f", 1.6)), 1.0, 2.2)
    do = _clamp(variables.get("object_distance", variables.get("distance", 5.0)),
                2.0 * f + 0.6, 6.6)   # beyond C → real, inverted, diminished
    ho = _clamp(variables.get("height", variables.get("object_height", 1.3)), 0.7, 1.8)

    di = 1.0 / (1.0 / f - 1.0 / do)   # do > f → real image
    hi = -ho * di / do
    return {"f": f, "do": do, "ho": ho, "di": di, "hi": hi}


def build(class_name: str, solver: Any) -> str | None:
    """Return a concave-mirror ray-diagram scene. Never needs solver data."""
    p = params(solver)
    f, do, ho, di, hi = p["f"], p["do"], p["ho"], p["di"], p["hi"]

    title = _shorten(getattr(solver, "summary", "") or "Concave-mirror image formation", 60)
    return _TEMPLATE.format(
        class_name=class_name,
        f=repr(round(f, 4)), do=repr(round(do, 4)), di=repr(round(di, 4)),
        ho=repr(round(ho, 4)), hi=repr(round(hi, 4)),
        title=repr(title),
    )


def _is_num(v: Any) -> bool:
    try:
        float(v)
        return True
    except (TypeError, ValueError):
        return False


def _clamp(value: Any, lo: float, hi: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        v = lo
    return max(lo, min(hi, v))


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - concave mirror ray diagram (curated component)."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        f, do, di = {f}, {do}, {di}
        ho, hi = {ho}, {hi}
        R = 2.0 * f   # radius of curvature; centre C is at x = -R (in front)

        title = Text({title}).scale(0.46).to_edge(UP)

        def P(x, y):
            return np.array([float(x), float(y), 0.0])

        axis = Line(P(-7.0, 0), P(1.2, 0), color=GREY_B, stroke_width=2, stroke_opacity=0.6)
        # Concave mirror: arc of radius R centred at C=(-R,0), vertex at origin.
        half = float(np.arcsin(min(2.0 / R, 0.98)))
        mirror = Arc(radius=R, start_angle=-half, angle=2 * half, arc_center=P(-R, 0),
                     color=BLUE_C, stroke_width=4)
        C = Dot(P(-R, 0), color=GREY_A, radius=0.05)
        F = Dot(P(-f, 0), color=GREY_A, radius=0.05)
        C_lbl = Text("C").scale(0.32).next_to(C, DOWN, buff=0.12)
        F_lbl = Text("F").scale(0.32).next_to(F, DOWN, buff=0.12)

        obj = Arrow(P(-do, 0), P(-do, ho), buff=0, color=GREEN, stroke_width=4)
        img = Arrow(P(-di, 0), P(-di, hi), buff=0, color=RED, stroke_width=4)
        obj_lbl = Text("object").scale(0.3).next_to(obj, UP, buff=0.1)
        img_lbl = Text("real image (inverted)").scale(0.3).next_to(img, DOWN, buff=0.1)

        tip = P(-do, ho)
        itip = P(-di, hi)
        # Ray 1: parallel to axis → reflects through F.
        ray1 = VMobject(color=YELLOW, stroke_width=2.5)
        ray1.set_points_as_corners([tip, P(0, ho), itip])
        # Ray 2: through F → reflects parallel to the axis.
        ray2 = VMobject(color=GOLD, stroke_width=2.5)
        ray2.set_points_as_corners([tip, P(0, hi), itip])
        # Ray 3: through C → hits the mirror perpendicular, reflects back on itself.
        ray3 = VMobject(color=ORANGE, stroke_width=2.5)
        ray3.set_points_as_corners([tip, itip])

        pulse = Dot(tip, color=WHITE, radius=0.06)

        self.play(Create(axis), Create(mirror), run_time=1.0)
        self.play(FadeIn(C), FadeIn(F), FadeIn(C_lbl), FadeIn(F_lbl), run_time=0.5)
        self.play(GrowArrow(obj), FadeIn(obj_lbl), run_time=0.7)
        self.play(Create(ray1), Create(ray2), Create(ray3), run_time=2.0)
        self.add(pulse)
        self.play(MoveAlongPath(pulse, ray1), run_time=1.4, rate_func=linear)
        self.play(GrowArrow(img), FadeIn(img_lbl), run_time=0.8)
        self.wait(0.6)
'''
