"""Curated component: kinetic theory — a gas of particles in a box.

Thermodynamics / statistical mechanics had no reliable (non-LLM) visual. This
stages an ideal gas: N particles bouncing elastically off the walls of a box
(seeded initial conditions integrated by a per-frame updater with wall
reflection), alongside a Maxwell–Boltzmann speed-distribution reference — the
microscopic picture behind temperature and pressure.

Deterministic (fixed seed) and self-contained (``manim`` + ``numpy`` only).
Selected on kinetic-theory / ideal-gas / thermodynamics phrasing.
"""

from __future__ import annotations

import math
from typing import Any

_N = 22


def params(solver: Any) -> dict[str, Any]:
    """Resolved particle count and temperature scaling; shared by build() and explain()."""
    variables = {str(k): v for k, v in dict(getattr(solver, "variables", {}) or {}).items()}
    n = variables.get("particles", variables.get("num_particles", variables.get("n", _N)))
    try:
        n = int(round(float(n)))
    except (TypeError, ValueError):
        n = _N
    # Hotter gas → faster particles: mean speed scales with sqrt(T) (T in K,
    # normalized to ~300 K room temperature).
    temperature = _positive(variables.get("temperature", variables.get("t")), None)
    speed_scale = _clamp(math.sqrt(temperature / 300.0), 0.55, 2.0) if temperature else 1.0
    return {"particles": max(8, min(40, n)), "temperature": temperature, "speed_scale": speed_scale}


def build(class_name: str, solver: Any) -> str | None:
    """Return a kinetic-theory scene; particle count & speed track the problem."""
    p = params(solver)
    n, speed_scale = p["particles"], p["speed_scale"]

    rng = _Rng(20260724)
    xmax, ymax = 3.1, 2.1
    particles = []
    for _ in range(n):
        px = (rng.random() * 2 - 1) * (xmax - 0.2)
        py = (rng.random() * 2 - 1) * (ymax - 0.2)
        speed = (1.4 + rng.random() * 1.8) * speed_scale
        ang = rng.random() * 2 * math.pi
        particles.append([
            round(px, 4), round(py, 4),
            round(speed * math.cos(ang), 4), round(speed * math.sin(ang), 4),
        ])

    title = _shorten(getattr(solver, "summary", "") or "Kinetic theory of an ideal gas", 60)
    return _TEMPLATE.format(
        class_name=class_name,
        particles=repr(particles),
        xmax=repr(xmax),
        ymax=repr(ymax),
        title=repr(title),
    )


def _positive(value: Any, default):
    try:
        v = float(value)
    except (TypeError, ValueError):
        return default
    return v if math.isfinite(v) and v > 1e-6 else default


def _clamp(value: Any, lo: float, hi: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        v = lo
    return max(lo, min(hi, v))


class _Rng:
    """Tiny deterministic LCG — avoids importing random for a fixed seed."""

    def __init__(self, seed: int) -> None:
        self._s = seed & 0xFFFFFFFF

    def random(self) -> float:
        self._s = (1103515245 * self._s + 12345) & 0x7FFFFFFF
        return self._s / 0x7FFFFFFF


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - kinetic theory (curated component)."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        xmax, ymax = {xmax}, {ymax}
        data = {particles}

        title = Text({title}).scale(0.44).to_edge(UP)
        box = Rectangle(width=2 * xmax, height=2 * ymax, color=GREY_A, stroke_width=3)
        box.shift(LEFT * 2.0)
        offset = box.get_center()

        particles = VGroup()
        for px, py, vx, vy in data:
            dot = Dot(offset + np.array([px, py, 0.0]), color=TEAL, radius=0.08)
            dot.velocity = np.array([vx, vy, 0.0])
            particles.add(dot)

        def step(mob, dt):
            dt = min(dt, 0.05)
            for d in mob:
                d.shift(d.velocity * dt)
                local = d.get_center() - offset
                if abs(local[0]) > xmax:
                    d.velocity[0] *= -1
                    d.shift(np.array([np.sign(local[0]) * (xmax - abs(local[0])), 0, 0]))
                if abs(local[1]) > ymax:
                    d.velocity[1] *= -1
                    d.shift(np.array([0, np.sign(local[1]) * (ymax - abs(local[1])), 0]))

        # Maxwell-Boltzmann speed distribution reference on the right.
        axes = Axes(
            x_range=[0, 4, 1], y_range=[0, 1.1, 0.5],
            x_length=3.6, y_length=2.6,
            axis_config={{"include_tip": False, "stroke_opacity": 0.5}},
        ).to_corner(DR, buff=0.6)
        a = 1.1
        mb = axes.plot(lambda v: (v * v) * np.exp(-(v * v) / (2 * a * a)) / (a ** 3) * 1.0,
                       x_range=[0.01, 4.0], color=GOLD)
        mb_label = Text("speed distribution").scale(0.3).next_to(axes, UP, buff=0.12)

        self.play(FadeIn(title), Create(box), run_time=0.9)
        self.play(LaggedStart(*[GrowFromCenter(d) for d in particles], lag_ratio=0.02),
                  run_time=1.2)
        self.play(Create(axes), Create(mb), FadeIn(mb_label), run_time=1.0)
        particles.add_updater(step)
        self.wait(5.5)
        particles.remove_updater(step)
        self.wait(0.3)
'''
