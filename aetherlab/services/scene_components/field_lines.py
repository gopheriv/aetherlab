"""Curated component: electric field lines of a point-charge configuration.

Electrostatics is not an initial-value ODE in time, so the numeric-trajectory
component never fires for it — yet it is one of the most recognisable physics
visuals. This integrates the field-line streamlines of a charge configuration
(a dipole by default) in Python — E(r) = Σ qᵢ (r − rᵢ) / |r − rᵢ|³, stepped along
the normalized field — and bakes the resulting polylines into a self-contained
Manim scene: the charges as +/- dots, the field lines threading from source to
sink, and a test charge that rides one line so the frame actually moves.

Deterministic, depends only on ``manim`` + ``numpy``. Selected when the solver's
domain is electrostatic (services/scene_templates.detect_domain == 'em_field').
"""

from __future__ import annotations

import math
from typing import Any

_SEEDS = 11          # field lines seeded around the positive charge
_MAX_STEPS = 260     # integration steps per line
_STEP = 0.05         # arc-length step (scene units)


def params(solver: Any) -> dict[str, float]:
    """Resolved charge separation; shared by build() and scenarios."""
    variables = {str(k): float(v) for k, v in dict(getattr(solver, "variables", {}) or {}).items()}
    sep = variables.get("separation", variables.get("distance", 2.4))
    try:
        sep = float(sep)
    except (TypeError, ValueError):
        sep = 2.4
    return {"separation": min(max(sep, 1.2), 3.6)}


def build(class_name: str, solver: Any) -> str | None:
    """Return a field-line scene for the solver's charge configuration, or None."""
    try:
        import numpy as np
    except Exception:  # noqa: BLE001
        return None

    sep = params(solver)["separation"]

    plus = np.array([-sep / 2.0, 0.0])
    minus = np.array([sep / 2.0, 0.0])
    charges = ((1.0, plus), (-1.0, minus))

    def field(point: "np.ndarray") -> "np.ndarray":
        total = np.zeros(2)
        for q, pos in charges:
            d = point - pos
            r = max(float(np.linalg.norm(d)), 0.22)
            total = total + q * d / (r ** 3)
        return total

    lines: list[list[list[float]]] = []
    for angle in np.linspace(-2.7, 2.7, _SEEDS):
        point = plus + 0.34 * np.array([math.cos(angle), math.sin(angle)])
        pts = [point.copy()]
        for _ in range(_MAX_STEPS):
            vec = field(point)
            norm = float(np.linalg.norm(vec))
            if norm < 1e-6:
                break
            point = point + _STEP * vec / norm
            pts.append(point.copy())
            if float(np.linalg.norm(point - minus)) < 0.34:
                break
            if abs(point[0]) > 6.4 or abs(point[1]) > 3.7:
                break
        if len(pts) >= 2:
            lines.append([[round(float(p[0]), 4), round(float(p[1]), 4)] for p in pts])

    if len(lines) < 3:
        return None

    # The longest line becomes the test-charge's path (guaranteed to move).
    ride = max(range(len(lines)), key=lambda i: len(lines[i]))
    title = _shorten(getattr(solver, "summary", "") or "Electric dipole field", 60)
    return _TEMPLATE.format(
        class_name=class_name,
        lines=repr(lines),
        ride=repr(ride),
        plus=repr([round(float(plus[0]), 4), round(float(plus[1]), 4)]),
        minus=repr([round(float(minus[0]), 4), round(float(minus[1]), 4)]),
        title=repr(title),
    )


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - electric field lines (curated component)."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        raw_lines = {lines}
        plus_pos = np.array({plus} + [0.0])
        minus_pos = np.array({minus} + [0.0])

        title = Text({title}).scale(0.5).to_edge(UP)

        field_lines = VGroup()
        paths = []
        for pts in raw_lines:
            points = [np.array([x, y, 0.0]) for x, y in pts]
            line = VMobject(color=BLUE_C, stroke_width=2.2)
            line.set_points_smoothly(points)
            field_lines.add(line)
            paths.append(line)

        plus = Dot(plus_pos, color=RED, radius=0.18)
        minus = Dot(minus_pos, color=BLUE, radius=0.18)
        plus_label = Text("+", color=WHITE).scale(0.5).move_to(plus_pos)
        minus_label = Text("-", color=WHITE).scale(0.6).move_to(minus_pos)

        ride = paths[{ride}]
        test_charge = Dot(ride.get_start(), color=YELLOW, radius=0.11)
        caption = Text("field lines run + source to - sink", color=GREY_A).scale(0.3)
        caption.to_edge(DOWN)

        self.play(GrowFromCenter(plus), GrowFromCenter(minus),
                  FadeIn(plus_label), FadeIn(minus_label), run_time=0.8)
        self.play(LaggedStart(*[Create(l) for l in field_lines], lag_ratio=0.08),
                  run_time=3.0)
        self.play(FadeIn(caption), run_time=0.5)
        self.add(test_charge)
        self.play(MoveAlongPath(test_charge, ride), run_time=2.6, rate_func=smooth)
        self.wait(0.5)
'''
