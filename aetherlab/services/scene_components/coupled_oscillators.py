"""Curated component: two coupled oscillators exchanging energy.

Two equal masses joined to the walls and to each other by springs form the
textbook coupled system. Started with one mass displaced, the energy sloshes
back and forth between them — the beat of the two normal modes (symmetric,
ω=√(k/m); antisymmetric, ω=√(3k/m)). This integrates the real coupled ODE
(state x₁, x₂, v₁, v₂) through the same scipy / AST-allow-listed path as every
other numeric result and bakes the exact motion into a Manim scene: two masses on
springs above, and the x₁(t)/x₂(t) traces below showing the energy transfer.

Depends only on ``manim`` + ``numpy``. Selected on coupled-oscillator /
normal-mode / two-mass phrasing.
"""

from __future__ import annotations

import math
from typing import Any

_MAX_POINTS = 300


def params(solver: Any) -> dict[str, float]:
    """Resolved spring constant and mass; shared by build() and explain()."""
    variables = {str(k): v for k, v in dict(getattr(solver, "variables", {}) or {}).items()}
    return {
        "stiffness": _positive(variables.get("stiffness", variables.get("k")), 1.0),
        "mass": _positive(variables.get("mass", variables.get("m")), 1.0),
    }


def build(class_name: str, solver: Any) -> str | None:
    """Return a coupled-oscillator scene, or None if it cannot integrate."""
    try:
        pass
    except Exception:  # noqa: BLE001
        return None

    p = params(solver)
    k, m = p["stiffness"], p["mass"]

    spec = {
        "state": ["x1", "x2", "v1", "v2"],
        "rhs": ["v1", "v2", "(-2*k*x1 + k*x2)/m", "(k*x1 - 2*k*x2)/m"],
        "initial": [1.0, 0.0, 0.0, 0.0],   # displace mass 1 only → energy beats over
        "t_range": [0.0, 24.0],
        "observe": "x1",
    }
    try:
        from aetherlab.services.numeric import solve_numeric

        sol = solve_numeric(spec, {"k": k, "m": m}, max_points=_MAX_POINTS)
    except Exception:  # noqa: BLE001 — composition must never crash the pipeline
        return None
    if not sol.ok or len(sol.t) < 12:
        return None

    ts = [round(float(v), 5) for v in sol.t]
    x1 = [round(float(v), 5) for v in sol.series("x1")]
    x2 = [round(float(v), 5) for v in sol.series("x2")]
    if not (len(ts) == len(x1) == len(x2)) or not all(_is_finite(v) for v in x1 + x2):
        return None

    title = _shorten(getattr(solver, "summary", "") or "Coupled oscillators (energy beats over)", 60)
    return _TEMPLATE.format(
        class_name=class_name,
        ts=repr(ts), x1=repr(x1), x2=repr(x2), title=repr(title),
    )


def _positive(value: Any, default: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        return default
    return v if math.isfinite(v) and v > 1e-6 else default


def _is_finite(v: float) -> bool:
    return v == v and v not in (float("inf"), float("-inf"))


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - coupled oscillators (curated component)."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        ts = {ts}
        x1s = {x1}
        x2s = {x2}
        disp = 0.9          # display scale for the mass displacements
        eq1, eq2 = -1.3, 1.3
        base_y = 1.4
        left_wall, right_wall = -4.4, 4.4

        title = Text({title}).scale(0.44).to_edge(UP)

        t = ValueTracker(float(ts[0]))

        def m1_x():
            return eq1 + disp * float(np.interp(t.get_value(), ts, x1s))

        def m2_x():
            return eq2 + disp * float(np.interp(t.get_value(), ts, x2s))

        def coil(x_start, x_end, n=6, amp=0.16):
            a = np.array([x_start, base_y, 0.0]); b = np.array([x_end, base_y, 0.0])
            out = [a]
            for i in range(1, 4 * n):
                f = i / (4 * n)
                mid = a + (b - a) * f
                out.append(mid + np.array([0.0, amp * (1 if i % 2 else -1), 0.0]))
            out.append(b)
            v = VMobject(color=GREY_B, stroke_width=2); v.set_points_as_corners(out); return v

        wallL = Line([left_wall, base_y - 0.6, 0], [left_wall, base_y + 0.6, 0], color=GREY_A, stroke_width=5)
        wallR = Line([right_wall, base_y - 0.6, 0], [right_wall, base_y + 0.6, 0], color=GREY_A, stroke_width=5)
        s_left = always_redraw(lambda: coil(left_wall, m1_x()))
        s_mid = always_redraw(lambda: coil(m1_x(), m2_x()))
        s_right = always_redraw(lambda: coil(m2_x(), right_wall))
        mass1 = always_redraw(lambda: Square(0.5, color=BLUE, fill_color=BLUE, fill_opacity=0.8).move_to([m1_x(), base_y, 0]))
        mass2 = always_redraw(lambda: Square(0.5, color=TEAL, fill_color=TEAL, fill_opacity=0.8).move_to([m2_x(), base_y, 0]))

        axes = Axes(
            x_range=[float(ts[0]), float(ts[-1]), (float(ts[-1]) - float(ts[0])) / 4.0],
            y_range=[-1.2, 1.2, 0.5], x_length=9.0, y_length=2.4,
            axis_config={{"include_tip": False, "stroke_opacity": 0.4}},
        ).to_edge(DOWN)
        c1 = VMobject(color=BLUE, stroke_width=3); c1.set_points_smoothly(
            [axes.coords_to_point(t_, x) for t_, x in zip(ts, x1s)])
        c2 = VMobject(color=TEAL, stroke_width=3); c2.set_points_smoothly(
            [axes.coords_to_point(t_, x) for t_, x in zip(ts, x2s)])
        sweep = always_redraw(lambda: DashedLine(
            axes.coords_to_point(t.get_value(), -1.2), axes.coords_to_point(t.get_value(), 1.2),
            color=GREY_B, stroke_width=1.5))
        lbl1 = Text("x1", color=BLUE).scale(0.3).next_to(axes, LEFT, buff=0.1).shift(UP * 0.5)
        lbl2 = Text("x2", color=TEAL).scale(0.3).next_to(axes, LEFT, buff=0.1).shift(DOWN * 0.5)

        self.play(FadeIn(title), Create(wallL), Create(wallR), run_time=0.8)
        self.add(s_left, s_mid, s_right, mass1, mass2)
        self.play(Create(axes), Create(c1), Create(c2), FadeIn(lbl1), FadeIn(lbl2), run_time=1.2)
        self.add(sweep)
        self.play(t.animate.set_value(float(ts[-1])), run_time=8.5, rate_func=linear)
        self.wait(0.4)
'''
