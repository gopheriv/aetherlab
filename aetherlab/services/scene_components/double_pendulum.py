"""Curated component: the chaotic double pendulum, driven by numeric truth.

The double pendulum is the iconic image of deterministic chaos. This integrates
the full nonlinear 4-state system (θ₁, θ₂, ω₁, ω₂) through the same scipy /
AST-allow-listed path as every other numeric result, then bakes the exact bob
positions into a self-contained Manim scene: two rods, two bobs, and a
``TracedPath`` on the lower bob painting the tell-tale tangled trajectory. The
motion is the real solution — sensitive to initial conditions — not a scripted
wiggle. Depends only on ``manim`` + ``numpy``.

Selected ahead of the single pendulum when the prompt says "double pendulum" or
"chaotic pendulum".
"""

from __future__ import annotations

import math
from typing import Any

_MAX_POINTS = 240

# Standard equal-friendly double-pendulum equations (state th1, th2, w1, w2).
_RHS = [
    "w1",
    "w2",
    ("(-g*(2*m1+m2)*sin(th1) - m2*g*sin(th1-2*th2) "
     "- 2*sin(th1-th2)*m2*(w2*w2*L2 + w1*w1*L1*cos(th1-th2))) "
     "/ (L1*(2*m1+m2-m2*cos(2*th1-2*th2)))"),
    ("(2*sin(th1-th2)*(w1*w1*L1*(m1+m2) + g*(m1+m2)*cos(th1) "
     "+ w2*w2*L2*m2*cos(th1-th2))) "
     "/ (L2*(2*m1+m2-m2*cos(2*th1-2*th2)))"),
]


def numeric_spec(initial: list[float] | None = None) -> dict[str, Any]:
    """The double-pendulum ODE animated by build(); explain() perturbs it."""
    return {
        "state": ["th1", "th2", "w1", "w2"],
        "rhs": _RHS,
        "initial": list(initial) if initial is not None else [2.2, 2.0, 0.0, 0.0],
        "t_range": [0.0, 12.0],
        "observe": "th1",
    }


def params(solver: Any) -> dict[str, float]:
    """Resolved arm lengths, masses and gravity; shared by build() and explain()."""
    variables = {str(k): float(v) for k, v in dict(getattr(solver, "variables", {}) or {}).items()}
    return {
        "g": _positive(variables.get("gravity", variables.get("g")), 9.81),
        "L1": _positive(variables.get("length", variables.get("length1", variables.get("l1"))), 1.0),
        "L2": _positive(variables.get("length2", variables.get("l2")), 1.0),
        "m1": _positive(variables.get("mass", variables.get("mass1", variables.get("m1"))), 1.0),
        "m2": _positive(variables.get("mass2", variables.get("m2")), 1.0),
    }


def build(class_name: str, solver: Any) -> str | None:
    """Return a chaotic double-pendulum scene, or None if it cannot integrate."""
    p = params(solver)
    g, L1, L2, m1, m2 = p["g"], p["L1"], p["L2"], p["m1"], p["m2"]

    spec = numeric_spec()
    try:
        from aetherlab.services.numeric import solve_numeric

        sol = solve_numeric(
            spec, {"g": g, "m1": m1, "m2": m2, "L1": L1, "L2": L2}, max_points=_MAX_POINTS
        )
    except Exception:  # noqa: BLE001 — composition must never crash the pipeline
        return None
    if not sol.ok or len(sol.t) < 3:
        return None

    th1 = [round(float(v), 5) for v in sol.series("th1")]
    th2 = [round(float(v), 5) for v in sol.series("th2")]
    if len(th1) != len(th2) or not all(_is_finite(v) for v in th1 + th2):
        return None

    title = _shorten(getattr(solver, "summary", "") or "Double pendulum (chaos)", 60)
    return _TEMPLATE.format(
        class_name=class_name,
        th1=repr(th1),
        th2=repr(th2),
        L1=repr(round(L1, 4)),
        L2=repr(round(L2, 4)),
        title=repr(title),
    )


def _positive(value: Any, default: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        return default
    return v if math.isfinite(v) and v > 1e-6 else default


def _is_finite(v: float) -> bool:
    return v == v and v not in (float("inf"), float("-inf"))


def _shorten(text: str, limit: int) -> str:
    compact = " ".join(str(text).split())
    return compact if len(compact) <= limit else compact[: limit - 1] + "…"


_TEMPLATE = '''\
"""Generated by AetherLab - chaotic double pendulum (curated component)."""

import numpy as np
from manim import *


class {class_name}(Scene):
    def construct(self):
        th1 = {th1}
        th2 = {th2}
        L1, L2 = {L1}, {L2}
        scale = 1.7 / max(L1 + L2, 1e-6)
        pivot = np.array([0.0, 1.6, 0.0])

        title = Text({title}).scale(0.46).to_edge(UP)

        idx = ValueTracker(0.0)

        def angles():
            i = idx.get_value()
            lo = int(np.floor(i)); hi = min(lo + 1, len(th1) - 1); f = i - lo
            a1 = th1[lo] * (1 - f) + th1[hi] * f
            a2 = th2[lo] * (1 - f) + th2[hi] * f
            return a1, a2

        def joints():
            a1, a2 = angles()
            p1 = pivot + scale * L1 * np.array([np.sin(a1), -np.cos(a1), 0.0])
            p2 = p1 + scale * L2 * np.array([np.sin(a2), -np.cos(a2), 0.0])
            return p1, p2

        anchor = Dot(pivot, color=GREY_B, radius=0.05)
        rod1 = always_redraw(lambda: Line(pivot, joints()[0], color=GREY_A, stroke_width=3))
        rod2 = always_redraw(lambda: Line(joints()[0], joints()[1], color=GREY_A, stroke_width=3))
        bob1 = always_redraw(lambda: Dot(joints()[0], color=BLUE, radius=0.13))
        bob2 = always_redraw(lambda: Dot(joints()[1], color=YELLOW, radius=0.15))
        trail = TracedPath(lambda: joints()[1], stroke_color=TEAL, stroke_width=2.5,
                           dissipating_time=3.0)
        caption = Text("sensitive to initial conditions", color=GREY_A).scale(0.3).to_edge(DOWN)

        self.play(FadeIn(title), FadeIn(caption), run_time=0.8)
        self.add(anchor, trail, rod1, rod2, bob1, bob2)
        self.play(idx.animate.set_value(float(len(th1) - 1)), run_time=8.5, rate_func=linear)
        self.wait(0.4)
'''
